"""Наружу уходит поисковая строка, а не то, что подвернулось в вердикте.

Найдено ревью уязвимых участков 2026-08-04, измерение «что уходит за пределы
машины». Класс тяжёлый: утечка личных данных в чужой поисковик необратима — она
уходит с машины и остаётся в чужих логах, сколько бы мы потом ни чистили у себя.

ДЕФЕКТ ПЕРВЫЙ. Вердикт арбитра — пара (вид, второе поле), и второе поле у разных
видов значит РАЗНОЕ: у «интернета» это поисковая строка, у «человека» — ИМЯ
участника, у «файла» — даты, у «правила» — текст указания. Бралось же оно как
запрос независимо от вида.

Ворота против имени в поисковике уже стояли — `_mentions_someone_from_the_archive`
— но только на ветке БЕЗ прямой просьбы поискать. На смешанной реплике («что там
Хасанов писал? и посмотри погоду на завтра») просьба есть, ворота пропускают ход,
и в поисковик уезжает фамилия сотрудника из архива. Ворота на одной дороге не
охраняют ничего.

ДЕФЕКТ ВТОРОЙ. Запасная строка (`web_query_from`) собирается вычёркиванием
вводных слов, то есть по сути является самой репликой человека, — и потолка у неё
не было вовсе, хотя у строки от арбитра он есть. Ветка не редкая: сюда приходят
все случаи, где арбитр строки не дал, включая его отказ и недоступность модели.

Оба дефекта — про ОГРАНИЧЕНИЕ УЩЕРБА. Ни один из них не про «система работает
неправильно»: она работает, и именно поэтому промах виден только замером того,
что уходит наружу.
"""

from __future__ import annotations

import inspect

import pytest

from friday.agent_runtime import AgentRuntime


@pytest.mark.parametrize(
    ("kind", "second"),
    [
        ("человек", "Хасанов"),
        ("человек", "Иванов Иван Иванович"),
        ("файл", "26.07,27.07"),
        ("правило", "не здороваться каждый раз"),
        ("архив", "поверка манометра"),
        ("быт", "чай"),
    ],
)
def test_only_the_internet_kind_gives_a_search_string(kind: str, second: str) -> None:
    """Мутация: снова брать второе поле у любого вида — тест краснеет.

    Проверяется САМО ПРАВИЛО отбора: у не-интернет видов второе поле не должно
    становиться поисковой строкой ни при каких условиях.
    """
    source = inspect.getsource(AgentRuntime._prefetch_the_web_if_asked)  # noqa: SLF001

    assert 'query = second if kind.startswith("интернет") else ""' in source, (
        "второе поле вердикта снова уходит в поисковик независимо от вида"
    )
    # Значение параметров здесь — документация случая: именно эти пары и уезжали.
    assert kind and second


def test_the_internet_kind_still_gets_its_query() -> None:
    """Обратная сторона: у вида «интернет» строка обязана доехать.

    Слишком строгая правка обнулила бы поиск целиком — и это было бы хуже утечки
    по частоте: человек перестал бы получать ответы о внешнем мире вовсе.
    """
    source = inspect.getsource(AgentRuntime._prefetch_the_web_if_asked)  # noqa: SLF001

    assert "kind, second = verdict" in source
    assert 'kind.startswith("интернет")' in source


@pytest.mark.parametrize(
    "message",
    [
        "найди в интернете " + "очень длинная строка про наши внутренние дела " * 10,
        "посмотри в интернете, вот что мне переслали: " + "текст договора с условиями " * 20,
    ],
)
def test_the_fallback_query_is_bounded(message: str) -> None:
    """Запасная строка — это почти вся реплика человека, и потолок ей нужен так же.

    ЧЕГО ЭТОТ ПОТОЛОК НЕ ДЕЛАЕТ, и это важно не перепутать: он НЕ защищает от
    короткой реплики с персональными данными. «Иванов Иван Иванович, 12.03.1985,
    паспорт 45 03 №123456 — проверь в интернете» укладывается в четырнадцать слов
    и уходит целиком, с потолком или без. Защита от такого — это ворота по имени
    из архива, и они отдельная история.

    Потолок здесь — про ДЛИННУЮ вставку: замерено, что переслаемое сообщение на
    1015 знаков уезжало в поисковик полностью. Ограничение ущерба, а не запрет.

    Мутация: снять потолок — тест краснеет.
    """
    query = AgentRuntime.web_query_from(message)

    assert len(query) <= 140, f"наружу уходит {len(query)} знаков"
    assert len(query.split()) <= 14, "наружу уходит вся реплика целиком"


def test_a_short_reply_with_personal_data_is_not_saved_by_the_bound() -> None:
    """Честная граница механизма: короткая строка проходит потолок целиком.

    Тест существует, чтобы следующий читатель не принял потолок за защиту
    персональных данных и не успокоился. Класс закрывается воротами по имени, а не
    длиной.
    """
    query = AgentRuntime.web_query_from(
        "Иванов Иван Иванович, 12.03.1985 — проверь в интернете, есть ли он в списке"
    )

    assert "Иванов Иван Иванович" in query, (
        "если это когда-нибудь перестанет быть правдой — потолок начал резать смысл, "
        "и надо перечитать, что именно он теперь обещает"
    )


def test_the_fallback_query_still_says_something() -> None:
    """Обрезка не должна превращать запрос в пустоту или в одно вводное слово."""
    query = AgentRuntime.web_query_from("найди в интернете какая сейчас ключевая ставка ЦБ")

    assert "ключевая ставка" in query
    assert "найди" not in query.casefold(), "вводные слова просьбы поисковику не нужны"


def test_the_bound_matches_the_arbiter_one() -> None:
    """Два пути наружу — один потолок.

    Разные пределы на двух дорогах к одному поисковику означают, что защита
    держится только на той, о которой вспомнили. Числа здесь совпадают
    намеренно: 14 слов и 140 знаков.
    """
    arbiter = inspect.getsource(AgentRuntime._web_query_by_arbiter)  # noqa: SLF001
    fallback = inspect.getsource(AgentRuntime.web_query_from)

    for source in (arbiter, fallback):
        assert "len(words) > 14" in source
        assert "[:140]" in source


def test_the_search_string_never_reaches_the_journal() -> None:
    """Поисковая строка не пишется в системный журнал — это записанное обещание.

    `docs/SECURITY.md` прямо говорит: «web_surfer логирует только hostname и класс
    исключения». Два места писали туда сам запрос, причём на уровне WARNING —
    то есть строка оставалась видимой даже у владельца, поднявшего порог
    логирования специально ради этого.

    Цена ошибки здесь особая: журнал не чистится ничем из нашего. Удаление знания,
    удаление сообщения и `purge` работают с базой, файлом и хранилищем — journald
    переживает их все, и «забыли по требованию человека» становится неправдой.
    """
    import inspect

    from friday.execution_kernel import ExecutionKernel
    from friday.web_surfer import WebSurfer

    for owner, name in ((ExecutionKernel, "_web_search"), (WebSurfer, "research")):
        source = inspect.getsource(getattr(owner, name))
        for line in source.splitlines():
            if "LOGGER" not in line or "refused" not in line:
                continue
            assert "query[:80]" not in line, f"{name}: запрос снова пишется в журнал"
            assert "%r" not in line or "query" not in line, f"{name}: запрос снова в журнале"
