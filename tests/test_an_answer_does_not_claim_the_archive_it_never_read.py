"""«По базе знаний» под ответом, в котором из базы нет ни строчки.

Найдено в живой переписке 2026-08-03. Человек попросил справку о сотруднике.
Пятница выдала учёную степень, звание и число научных работ, подав это словами
«по базе знаний». Ссылок `[K#]` — ноль, `answer_grounded` — False. Человек ответил
«неправильно составила справку». Днём раньше та же манера назвала неверную дату
профессионального праздника — и её он тоже поправил сам.

Проверять такое судьёй не нужно и нечем: при пустых данных судья обязан
забраковать всё подряд, и ровно поэтому в таких ходах его не зовут — иначе
предупреждение появлялось бы под каждым ответом о внешнем мире и обесценивало те,
что по делу. Замерено: из четырёх ответов, сославшихся на базу словами, ТРИ не
получили никакого предупреждения вовсе.

Но само утверждение о ПРОИСХОЖДЕНИИ проверяется точно и без модели: ссылок ноль —
значит из архива не пришло ничего — значит фраза ложна. Это тот же приём, что и у
`_strip_invented_citations`: структурный перехват заведомо неверного утверждения,
а не попытка распознать смысл списком слов.

Отдельно проверяется обратная сторона: честные фразы про архив («в базе ничего не
нашлось») и законные ссылки на внешние источники («по данным Росстата») не должны
попадать под правило. Предупреждение не по делу обесценивает те, что по делу, —
на этом проекте за это уже приходилось возвращаться дважды.
"""

from __future__ import annotations

import pytest

from friday.agent_runtime import _CLAIMS_THE_ARCHIVE, _grounding_warning

FALSE_CLAIMS = [
    "по базе знаний он родился в 1970 году",
    "согласно базе знаний, звание — полковник",
    "из базы знаний: более 50 научных работ",
    "судя по вашим документам, срок вышел",
    "опираясь на ваши записи, могу сказать",
    "по вашему архиву дата другая",
    "согласно личным материалам, это так",
]

HONEST = [
    "в базе знаний нет данных об этом",
    "в вашей базе ничего не нашлось",
    "база знаний пуста",
    "я не нашла в архиве ничего по этому вопросу",
    "по данным Росстата инфляция составила 4%",
    "согласно приказу 214 срок продлён",
    "по вашим словам, вы уезжаете в среду",
    "судя по всему, это опечатка",
    "насколько я знаю, праздник в ноябре",
]


@pytest.mark.parametrize("text", FALSE_CLAIMS)
def test_a_claim_on_the_archive_is_recognised(text: str) -> None:
    assert _CLAIMS_THE_ARCHIVE.search(text), f"ложная ссылка прошла незамеченной: {text!r}"


@pytest.mark.parametrize("text", HONEST)
def test_honest_wording_is_left_alone(text: str) -> None:
    """Ложная тревога дороже пропуска: её видят под каждым ответом."""
    assert not _CLAIMS_THE_ARCHIVE.search(text), f"честная фраза принята за ложную: {text!r}"


def test_the_warning_fires_where_three_of_four_stayed_silent() -> None:
    """Главный случай: поиск не нашёл НИЧЕГО, поэтому `answer_grounded` — None.

    Обе прежние ветки на `None` молчат, и человек не получал ни ссылок, ни
    предупреждения — только уверенную справку с выдуманными числами.

    Мутация, которую тест обязан ловить: убрать проверку `_CLAIMS_THE_ARCHIVE`.
    """
    text = _grounding_warning("По базе знаний: звание — полковник, работ более 50.", None)

    assert text, "ответ соврал о происхождении и не получил ни одного предупреждения"
    assert "не так" in text and "не найдено ни одной" in text


def test_a_grounded_answer_is_not_scolded() -> None:
    """Живая ссылка [K1] — значит из архива действительно пришло. Молчим."""
    text = _grounding_warning("По базе знаний [K1] срок поверки — до марта.", True)

    assert text == ""


def test_an_ordinary_ungrounded_answer_still_says_nothing() -> None:
    """Ответ о внешнем мире без ссылок — законный, и предупреждать не о чем.

    Владелец просил убрать эту пометку дважды: она появлялась под каждым ответом
    про курс доллара. Правка не имеет права её вернуть.
    """
    text = _grounding_warning("Курс доллара сегодня около 79 рублей.", False)

    assert text == ""


def test_the_model_is_told_not_to_invent_the_attribution() -> None:
    """Перехват — вторая линия. Первая — не сочинять ссылку вовсе."""
    from friday.agent_runtime import SYSTEM_PROMPT

    assert "НИКОГДА не приписывай ответ архиву" in SYSTEM_PROMPT
    assert "насколько я знаю" in SYSTEM_PROMPT, "не сказано, КАК говорить честно"
