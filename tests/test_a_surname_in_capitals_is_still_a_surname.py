"""Фамилия, набранная заглавными, — тоже фамилия.

В служебных документах фамилию печатают капслоком: «ЛЯПИН Александр
Александрович», «МОИСЕЕВ Алексей Алексеевич». Первая ветка правила про ФИО
требовала `[А-ЯЁ][а-яё-]` и такое имя не брала — зато срабатывала ВТОРАЯ, «Имя
Отчество Фамилия», и приклеивала к человеку следующее слово таблицы:

    ЛЯПИН Александр Александрович Наводчик   → «Александр Александрович Наводчик»
    МЕДВЕДЕВ Александр Вячеславович Подпись  → «Александр Вячеславович Подпись»
    КУШНАЗАРОВ Анатолий Олегович Вакансия    → «Анатолий Олегович Вакансия»
    ИЗЫГАШЕВ Максим Александрович Судимость  → «Максим Александрович Судимость»

Замерено на всех 1536 живых документах, обе регулярки прогнаны рядом:

    различных ФИО      4376 → 8987
    упоминаний        21461 → 45162
    обрывков            168 → 9
    пропало имён             159 — все до одного обрывки вида «Имя Отчество Хвост»

Правило не просто плодило мусор: оно отдавало мусор ВМЕСТО человека. Из имён с
заглавной фамилией 2571 не имели в графе ни одного узла — то есть две с половиной
тысячи людей архива были системе не видны.
"""

from __future__ import annotations

from friday.ingestion._base import _extract_entities


def _people(text: str) -> set[str]:
    return {
        str(item["name"])
        for item in _extract_entities(text)
        if str(item["entity_type"]) == "person" and str(item["method"]) == "explicit_person_patronymic"
    }


def test_a_capitalised_surname_makes_a_whole_person():
    names = _people("1 мотострелкового батальона Рядовой ЛЯПИН Александр Александрович Наводчик")
    assert "ЛЯПИН Александр Александрович" in names
    assert "Александр Александрович Наводчик" not in names


def test_a_form_field_heading_is_not_a_surname():
    names = _people("рядовой МЕДВЕДЕВ Александр Вячеславович Подпись лица, проводившего поверку")
    assert "МЕДВЕДЕВ Александр Вячеславович" in names
    assert not any(name.endswith("Подпись") for name in names)


def test_an_empty_roster_row_is_not_a_surname():
    names = _people("КУШНАЗАРОВ Анатолий Олегович Вакансия 8 Вакансия 9 ХОРЕНЯН Арам Ашотович")
    assert "КУШНАЗАРОВ Анатолий Олегович" in names
    assert "Анатолий Олегович Вакансия" not in names


def test_two_people_in_a_row_do_not_merge_into_one():
    """Соседние записи таблицы не сшиваются в несуществующего человека."""
    names = _people("МИХАЙЛОВ Александр Александрович ХАСАНОВ Руслан Рашитович")
    assert "МИХАЙЛОВ Александр Александрович" in names
    assert "ХАСАНОВ Руслан Рашитович" in names
    assert "Александр Александрович ХАСАНОВ" not in names


def test_the_ordinary_case_still_works():
    """Обычное написание не должно пострадать: правка только про регистр."""
    names = _people("Заявление подал Игнатов Василий Владимирович вчера")
    assert "Игнатов Василий Владимирович" in names


def test_name_first_order_is_still_read():
    """Вторая ветка нужна: «Имя Отчество Фамилия» встречается в письмах."""
    names = _people("Прошу Вас, Василий Владимирович Игнатов, рассмотреть заявление")
    assert "Василий Владимирович Игнатов" in names


def test_capitals_and_ordinary_spelling_are_one_node():
    """Дублей не будет: тождество узла считает `normalize_entity_name`."""
    from friday.storage._base import normalize_entity_name

    assert normalize_entity_name("ИГНАТОВ Василий Владимирович") == normalize_entity_name(
        "Игнатов Василий Владимирович"
    )
