"""Тег имеет смысл ровно настолько, насколько по нему можно ОТБИРАТЬ.

Замер на живом архиве владельца (1536 объектов, 15 900 экземпляров тегов): 75 из
100 самых частых тегов не несут темы вовсе — это 52% всего тегового объёма.
Разбивка по источникам: служебные слова 843 экземпляра, обрывки ФИО 901, названия
граф бланка 1751, обрывки словосочетаний 1747.

Отсюда три отсева, и каждый закрывает СВОЙ класс. Ниже проверяется, что ни один
не подменяет другой: список служебных слов не лечит имена, частота не лечит
служебные слова (замерено: «рапорт» в 20.6% документов, «нет» — в 18%).
"""

from __future__ import annotations

from friday.ingestion._base import _extract_keywords

_RAPORT = (
    "РАПОРТ\n"
    "Прошу Вас разрешить убытие рядового Иванова Сергея Александровича "
    "в отпуск за пределы гарнизона. Командиру батальона. Командир роты "
    "уведомлен, командира взвода прошу назначить старшим.\n"
)


def test_service_words_are_not_topics():
    """«при», «года», «нет», «где», «прошу» стояли тегами на 130–181 объекте."""

    tags = _extract_keywords("При этом в течение года нет данных о том, где именно прошу считать")
    assert not {"при", "года", "нет", "где", "прошу"} & set(tags)


def test_parts_of_a_persons_name_are_not_topics():
    """Имена знает граф; «александрович» стоял тегом на 194 объектах.

    Тег, повторяющий имя, не добавляет ни одного нового отбора — только вытесняет
    с экрана осмысленные.
    """

    blocked = frozenset({"иванова", "сергея", "александровича"})
    tags = _extract_keywords(_RAPORT, blocked=blocked)
    assert not {"иванова", "сергея", "александровича"} & set(tags)
    assert "убытие" in tags


def test_one_notion_is_one_tag():
    """«командиру», «командир», «командира» — одно понятие в трёх тегах.

    На живом архиве один «командир» размазан по семи формам на 457 экземпляров.
    На экране выбора это семь чипов там, где понятие одно.
    """

    tags = _extract_keywords(_RAPORT)
    assert sum(1 for tag in tags if tag.startswith("командир")) == 1


def test_a_word_that_is_everywhere_selects_nothing():
    """Слово из почти каждого документа корпуса выбор не сужает."""

    text = "Поверка приборов в подразделении. Поверка проведена, приборы исправны."
    everywhere = {"поверка": 900, "приборы": 40, "приборов": 40}
    tags = _extract_keywords(text, document_frequency=everywhere, corpus_size=1000)
    assert "поверка" not in tags
    assert any(tag.startswith("прибор") for tag in tags)


def test_frequency_alone_cannot_replace_the_service_word_list():
    """Замер, из-за которого отсевы нельзя схлопнуть в один.

    «рапорт» стоит в 316 документах из 1536 (20.6%), «нет» — в 279 (18%). Первое
    — тема, второе — служебное слово, и НИКАКОЙ порог их не различает: между ними
    либо оба остаются, либо оба уходят. Здесь при пороге 0.15 уходят оба — но
    «нет» ушло бы и без порога, списком, а «рапорт» уходит только по частоте, и
    его место занял точный `вид:рапорт`.
    """

    text = "Рапорт подан. Нет оснований отказать. Рапорт рассмотрен."
    frequency = {"рапорт": 316, "нет": 279}
    tags = _extract_keywords(text, document_frequency=frequency, corpus_size=1536)
    assert "нет" not in tags
    assert "рапорт" not in tags
    # Без корпусной частоты слово остаётся: отсев именно частотный, а не списочный.
    assert "рапорт" in _extract_keywords(text)


def test_an_empty_result_is_better_than_a_wrong_one():
    """Из текста, где нет ничего, кроме служебных слов, тегов не берётся."""

    assert _extract_keywords("И вот это то, что было бы при этом же") == []
