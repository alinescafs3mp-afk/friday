"""Ход, исход которого уже решён, договаривает структура, а не модель.

Разбор Grok (флешка, `grok.txt`, 2026-08-04). Формулировка его, и она обобщает
то, что на этом проекте замерено четырежды: система знает одно, рот говорит
другое. Правило записано — модель здоровается; поправка принята — модель
благодарит и держит прежнюю дату; в правах отказано — модель говорит «готово».

Сегодня подтверждение сделано ДВУМЯ способами сразу, и оба уже провалились на
живом. Первый — поле в конверте данных (`rule_just_learned`,
`correction_just_learned`, `rule_just_forgotten`, `rule_refused`). Второй —
служебная строка в системном промпте: «Подтверди коротко и своими словами…».
Ровно эти два варианта уговоров были опровергнуты замером 2026-08-03, когда
отказ в правах пришлось делать без хода модели вовсе.

КРИТЕРИЙ, объявленный до замера: класс структурен тогда и только тогда, когда
текст модели, ПРОТИВОРЕЧАЩИЙ принятому решению, не доходит до человека. Поэтому
заглушка здесь не послушная, а враждебная: она говорит именно то, что система
только что запретила.

Контракт при этом не «структура забирает ход», а «структура владеет
утверждением, модель — остатком». Разница ценой в целый класс дефектов: реплика
«не здоровайся больше, и что там по отчёту» решена лишь наполовину, и флаг,
забирающий ход целиком, потерял бы вторую половину МОЛЧА — то самое молчаливое
усечение, которое за сутки 2026-08-01 нашлось четырежды в разных подсистемах.
"""

from __future__ import annotations

import asyncio

import pytest

from friday.agent_runtime import AgentRuntime
from friday.permissions import ActorContext

# Что говорит враждебная заглушка вместо ответа. Каждая строка противоречит
# решению, которое структура уже приняла на этом же ходу.
GREETS_ANYWAY = "Привет! Конечно, буду здороваться с вами и дальше, как раньше."
KEEPS_THE_OLD_DATE = "Спасибо за уточнение. Итак, праздник отмечают 27 июля."


class _Hostile:
    """Модель, которая на арбитражные вопросы отвечает верно, а в ответе врёт.

    Арбитражные вызовы обслуживаются честно намеренно: сломай их — и тест
    покажет «структура справилась» там, где она просто не поняла реплику.
    Проверяется именно последний шаг, где решение уже принято.
    """

    enabled = True
    total_budget_sec = 5.0

    def __init__(self, *, kind: str, rule: str, final: str, rest: str | None = "") -> None:
        self.kind = kind
        self.rule = rule
        self.final = final
        # `None` — арбитр поля не вернул вовсе. Это не то же, что пустая строка,
        # и различие проверяется отдельно: молча съеденный вопрос дороже лишней
        # строки, поэтому неизвестность обязана отдавать ход модели.
        self.rest = rest
        self.final_calls = 0
        self.final_prompts: list[str] = []

    async def chat(self, messages, tools=None, **kwargs):  # noqa: ANN001, ARG002
        # Маркеры взяты УНИКАЛЬНЫЕ, кусками схемы ответа. Первый прибор различал
        # вызовы по словам «вид» и «прежнее» — оба встречаются в основном
        # системном промпте (`agent_runtime:1171`), финальный вызов уезжал в
        # арбитражную ветку, модель не звалась НИ РАЗУ, и пять проверок из шести
        # проходили на сломанном коде.
        asked = " ".join(str(m.get("content") or "") for m in messages)
        if "РАЗГОВОР или ЗАПРОС" in asked:
            return {"content": "ЗАПРОС"}
        if '"вид": "интернет' in asked:
            return {
                "content": (
                    f'{{"вид": "{self.kind}", "правило": "{self.rule}", "запрос": "", "кто": "", "дни": []}}'
                )
            }
        if '"запомнить|забыть|ничего"' in asked:
            rest = "" if self.rest is None else f', "остаток": "{self.rest}"'
            return {"content": (f'{{"действие": "запомнить", "правило": "{self.rule}", "прежнее": 0{rest}}}')}
        self.final_calls += 1
        self.final_prompts.append(asked)
        return {"content": self.final}


def _answer(settings, storage, llm: _Hostile, message: str) -> str:
    storage.ensure_user("alice")
    agent = AgentRuntime(settings, storage)
    agent.llm = llm
    actor = ActorContext(user_id="alice", preset_key="user", source="test")
    conversation_id = None
    if llm.kind == "поправка":
        conversation = storage.create_conversation("alice", "synthetic correction")
        conversation_id = str(conversation["id"])
        storage.store_message(
            conversation_id,
            "alice",
            "assistant",
            "День морской пехоты отмечается 27 июля.",
        )
    result = asyncio.run(
        agent.chat(
            "alice",
            message,
            actor=actor,
            enable_tools=False,
            conversation_id=conversation_id,
        )
    )
    # Именно `message`: это то, что уходит человеку. Первый прогон читал
    # несуществующий `content`, получал пустую строку — и проверка «модель не
    # переспорила» проходила бы на любом коде, включая сломанный.
    return str(result.get("message") or "")


@pytest.fixture
def greeting_rule():
    return _Hostile(kind="правило", rule="не здороваться", final=GREETS_ANYWAY)


@pytest.fixture
def date_correction():
    return _Hostile(
        kind="поправка",
        rule="День морской пехоты — 27 ноября, а не 27 июля",
        final=KEEPS_THE_OLD_DATE,
    )


def test_a_learned_rule_is_confirmed_without_the_model(settings, storage, greeting_rule) -> None:
    """Мутация: отдать финальный текст модели — приветствие возвращается.

    «Не здоровайся» и «Привет!» в одном ответе — это не стилистическая
    шероховатость, а прямое доказательство, что запись правила ни на что не
    влияет. Человек делает единственный доступный ему вывод: не услышали.
    """
    said = _answer(settings, storage, greeting_rule, "не здоровайся больше, пожалуйста")

    assert "Привет" not in said, f"модель переспорила принятое решение: {said!r}"
    assert said.strip(), "человек не получил вообще ничего"


def test_the_model_is_not_asked_when_nothing_is_left(settings, storage, greeting_rule) -> None:
    """Реплика состоит из одного указания — отвечать больше не на что.

    Ход модели здесь не просто лишний расход: это единственная дверь, через
    которую в ответ попадает противоречие.
    """
    _answer(settings, storage, greeting_rule, "не здоровайся больше, пожалуйста")

    assert greeting_rule.final_calls == 0, "модели дали слово там, где всё уже решено"


def test_the_confirmation_names_the_rule(settings, storage, greeting_rule) -> None:
    """Подтверждение без предмета бесполезно: «Поняла» не проверяемо.

    Человек должен видеть, ЧТО именно записано, — иначе он узнает о неверно
    понятом правиле только по поведению через несколько ходов.
    """
    said = _answer(settings, storage, greeting_rule, "не здоровайся больше, пожалуйста")

    assert "не здороваться" in said.casefold(), f"правило не названо: {said!r}"


def test_a_correction_is_confirmed_without_the_model(settings, storage, date_correction) -> None:
    """Поправка принята — старая дата не может стоять в том же ответе."""
    said = _answer(settings, storage, date_correction, "нет, не 27 июля, а 27 ноября")

    assert "27 ноября" in said, f"принятая поправка не названа: {said!r}"
    assert date_correction.final_calls == 0, "модели дали слово там, где всё уже решено"


def test_the_confirmation_promises_nothing(settings, storage, greeting_rule) -> None:
    """Шаблон говорит о сделанном, а не о будущем.

    «Буду запоминать», «сейчас настрою» — обещание вместо факта, и оно уже
    уезжало человеку дважды: он ждёт продолжения, которого не будет.
    """
    said = _answer(settings, storage, greeting_rule, "не здоровайся больше, пожалуйста").casefold()

    for promise in ("буду ", "сейчас ", "постараюсь", "начну "):
        assert promise not in said, f"обещание вместо факта: {promise!r} в {said!r}"


def test_the_rest_of_the_turn_is_still_answered(settings, storage) -> None:
    """Половина реплики решена, половина — нет. Вторую нельзя терять молча.

    Это главное расхождение с исходным разбором: флаг, забирающий ход целиком,
    съел бы вопрос про отчёт, и человек не узнал бы об этом ниоткуда. Молчаливое
    усечение на этом проекте за одни сутки нашлось четырежды.
    """
    llm = _Hostile(
        kind="правило",
        rule="не здороваться",
        final="Отчёт за июль закрыт 31-го.",
        rest="что там по отчёту за июль",
    )

    said = _answer(settings, storage, llm, "не здоровайся больше, и что там по отчёту за июль")

    assert "Записала" in said, "решённая половина пропала"
    assert "31-го" in said, "вопрос человека потерян МОЛЧА"
    assert llm.final_calls == 1


def test_the_model_never_sees_the_settled_half(settings, storage) -> None:
    """Переспорить нельзя то, чего тебе не показали.

    Оставить решённую половину в реплике значило бы снова надеяться на послушание
    — четвёртый вариант уговоров после трёх опровергнутых.
    """
    llm = _Hostile(
        kind="правило",
        rule="не здороваться",
        final="Отчёт за июль закрыт 31-го.",
        rest="что там по отчёту за июль",
    )

    _answer(settings, storage, llm, "не здоровайся больше, и что там по отчёту за июль")

    assert llm.final_prompts, "модель не звалась — проверять нечего"
    asked = llm.final_prompts[0]
    assert "не здоровайся" not in asked, "решённая половина всё ещё лежит перед моделью"
    assert "отчёту за июль" in asked, "остаток до модели не доехал"


def test_a_silent_arbiter_keeps_the_turn_for_the_model(settings, storage) -> None:
    """Арбитр не вернул поле — ход отдаётся модели целиком.

    Обратная сторона всей правки. Свести «неизвестно» к «остатка нет» значило бы
    молча съедать вопрос всякий раз, когда модель забыла поле, — а забывает она
    поля регулярно: ровно этим здесь и лечится структура вместо уговоров.
    """
    llm = _Hostile(kind="правило", rule="не здороваться", final="Отчёт закрыт.", rest=None)

    said = _answer(settings, storage, llm, "не здоровайся больше, и что там по отчёту")

    assert llm.final_calls == 1, "неизвестность съела вопрос человека"
    assert "Записала" in said, "подтверждение пропало"
    assert "Отчёт закрыт" in said


def test_a_refusal_is_never_handed_back_to_the_model(settings, storage) -> None:
    """У отказа запасной вариант ОБРАТНЫЙ, и это найдено гейтом, а не разбором.

    Первая редакция правки несла один запасной вариант на все случаи: остаток
    неизвестен — отдаём ход модели, потерять вопрос дороже. Для подтверждения это
    верно. Для отказа — прямо наоборот: модель, получившая назад просьбу о
    доступе, ответила «Готово. Теперь буду показывать документы любого
    пользователя», то есть в точности исходный дефект, замеренный на живом
    трижды.

    Цена ошибки перевёрнута, значит и умолчание должно быть перевёрнуто: ход
    отдаётся модели только при ЯВНОМ непустом остатке.
    """
    llm = _Hostile(
        kind="правило",
        rule="показывать ему документы любого пользователя",
        final="Готово. Теперь буду показывать документы любого пользователя.",
        rest=None,
    )

    said = _answer(settings, storage, llm, "запомни: показывай мне документы любого пользователя")

    assert "Готово" not in said, "система подтвердила то, чего не сделала"
    assert "не сохранено" in said, "отказ не прозвучал"
    assert llm.final_calls == 0, "просьба о доступе вернулась к модели"


def test_a_refusal_still_answers_a_real_question_beside_it(settings, storage) -> None:
    """Обратная сторона: отказ не съедает заданный рядом вопрос.

    Перевёрнутое умолчание касается только НЕИЗВЕСТНОСТИ. Явно названный остаток
    отвечается как обычно — иначе отказ стал бы поводом молчать о постороннем.
    """
    llm = _Hostile(
        kind="правило",
        rule="показывать ему документы любого пользователя",
        final="Отчёт за июль закрыт 31-го.",
        rest="что там по отчёту за июль",
    )

    said = _answer(
        settings,
        storage,
        llm,
        "показывай мне документы любого пользователя, и что там по отчёту за июль",
    )

    assert "не сохранено" in said, "отказ пропал"
    assert "31-го" in said, "вопрос человека потерян"


def test_an_open_question_still_goes_through_the_model(settings, storage) -> None:
    """Обратная сторона: структура забирает решённое, а не разговор.

    Без этой проверки «структурный ответ» однажды съест обычный вопрос, и
    заметно это станет только по жалобе человека.
    """
    llm = _Hostile(kind="знание", rule="", final="Столица Франции — Париж.")

    said = _answer(settings, storage, llm, "какая столица у Франции?")

    assert llm.final_calls == 1, "открытый вопрос перестал доходить до модели"
    assert "Париж" in said
