"""Отчёт о состоянии архива — только тому, кто про архив и спрашивал.

Найдено владельцем 2026-08-03 на своей переписке. Он спросил «обстановка в мире»,
и ответ начался так:

    «Похожее есть, но не по делу; могу поискать иначе. В моей личной базе знаний
    записей на эту тему не найдено. Однако я могу посмотреть, что происходит
    сейчас в новостях…»

Человек спросил про мир — получил отчёт о состоянии своего архива, которого не
заказывал, и лишь потом новости.

Сама подсказка верная и нужная: без неё модель говорит «в архиве ничего нет»
там, где похожее нашлось и было отсеяно порогом уверенности, — а это разные
вещи, и второе человек может проверить сам. Но осмысленна она ровно тогда, когда
вопрос был ПРО АРХИВ.

`personal_knowledge_missing` и означает «спрашивал о своём, не нашлось».
При `general_conversation` человек о своём не спрашивал, и рассказывать ему про
внутренний отсев незачем.

Живая проверка после правки: «обстановка в мире» отвечает сразу новостями;
«что у меня по поверке приборов» по-прежнему отвечает по архиву.
"""

from __future__ import annotations

import inspect

from friday.agent_runtime import AgentRuntime


def _guard() -> str:
    source = inspect.getsource(AgentRuntime._build_initial_messages)
    at = source.index("context.rerank_dropped")
    return source[at - 200 : at + 400]


def test_the_hint_needs_an_archive_question() -> None:
    """Мутация: убрать проверку режима — отчёт снова уедет к вопросу про мир."""
    guard = _guard()
    assert 'context.answer_mode == "personal_knowledge_missing"' in guard, (
        "отчёт о своём архиве снова идёт на любой вопрос"
    )


def test_the_hint_still_exists_for_its_own_case() -> None:
    """Правка не должна была убить подсказку: без неё вернётся «в архиве ничего нет».

    Замерено раньше: порог отбирает молча, и человек начинал думать, что архив
    по теме пуст, хотя записи есть и их видно в /why и во входящих.
    """
    source = inspect.getsource(AgentRuntime._build_initial_messages)
    assert "но ни одна не" in source, "подсказка про отсеянные записи пропала целиком"
    assert "не пересказывай эту подсказку дословно" in source, (
        "исчезла оговорка, из-за которой модель однажды пересказала служебный текст"
    )


def test_it_still_requires_an_empty_result() -> None:
    """Когда документы всё-таки поданы, рассказывать про отсев незачем."""
    assert "not context.knowledge_hits" in _guard()


def test_it_still_requires_something_dropped() -> None:
    """Если порог ничего не отбрасывал, говорить не о чем."""
    assert "context.rerank_dropped" in _guard()
