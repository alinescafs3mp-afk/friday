"""«Организация управления» — это действие, а не учреждение.

Слово-объявитель «организация» по-русски значит и «учреждение», и «налаживание».
В служебных документах почти всегда второе, и стоит оно в заголовке раздела:

    3. ОРГАНИЗАЦИЯ УПРАВЛЕНИЯ
    5. ОРГАНИЗАЦИЯ ПРОВЕДЕНИЯ СОРЕВНОВАНИЙ
    2. ОРГАНИЗАЦИЯ УСИЛЕНИЯ ОХРАНЫ И ОБОРОНЫ

Замерено на архиве владельца: правило «организация X» завело РОВНО ПЯТЬ имён, и
все пять — заголовки разделов. Ни одного верного. «УПРАВЛЕНИЯ» при этом сидело в
160 документах и лезло в каждую картину графа как организация.

Различает падеж, а не список слов: за учреждением следует имя в именительном
(«организация Красный Крест»), за действием — родительный. Это отличает форму,
которую документ ОБЪЯВЛЯЕТ, от совпадения слов — ровно то, чем этот проект
заменяет затыкание регулярками.
"""

from __future__ import annotations

from friday.ingestion._base import _extract_entities


def _organisations(text: str) -> set[str]:
    return {
        str(item["name"])
        for item in _extract_entities(text)
        if str(item["entity_type"]) == "organization"
    }


def test_a_section_heading_is_not_an_organisation():
    assert _organisations("3. ОРГАНИЗАЦИЯ УПРАВЛЕНИЯ") == set()
    assert _organisations("5. ОРГАНИЗАЦИЯ ПРОВЕДЕНИЯ СОРЕВНОВАНИЙ") == set()
    assert _organisations("2. ОРГАНИЗАЦИЯ УСИЛЕНИЯ ОХРАНЫ И ОБОРОНЫ") == set()


def test_an_adjective_in_the_genitive_is_caught_too():
    """«ОРГАНИЗАЦИЯ БОЕВОЙ ПОДГОТОВКИ»: падеж несёт первое слово группы."""
    assert _organisations("ОРГАНИЗАЦИЯ БОЕВОЙ ПОДГОТОВКИ") == set()


def test_a_real_organisation_is_still_extracted():
    """Сужение не должно съесть то, ради чего правило написано."""
    assert "Красный Крест" in _organisations("организация Красный Крест помогает")
    assert "Мемориал" in _organisations("организация Мемориал закрыта")


def test_a_company_is_untouched():
    """«Компания» и «фирма» действиями не бывают — их сужать не за что."""
    assert "Яндекс" in _organisations("компания Яндекс наняла сотрудников")
    assert "Ромашка" in _organisations("фирма Ромашка поставила товар")
