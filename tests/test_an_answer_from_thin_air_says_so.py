"""Ответ, под которым нет ни одной записи, честно говорит об этом.

НАЙДЕНО ВЛАДЕЛЬЦЕМ 2026-08-04. Вопрос о начале разговора с другим участником
получил уверенный ответ, в котором первая реплика ЕГО ЖЕ текущей беседы выдана за
чужую. Метки того хода: вид «архив», ноль записей, ноль сущностей, ни одного
вызова инструмента, уверенность поиска 0.0 — и при этом ни предупреждения, ни
судьи.

Прежние предохранители молчали здесь ПО ПОСТРОЕНИЮ, и это главное в разборе:

* `answer_grounded` равен `None`, когда поиск не нашёл ничего, — обе ветки,
  завязанные на `False`, не срабатывают;
* обвинение в ложной ссылке на архив ставится по СЛОВАМ ответа, а тот про архив
  ничего не утверждал: он просто соврал уверенно;
* судья при пустых данных обязан забраковать всё подряд, поэтому его в таких
  ходах намеренно не зовут.

Признак поэтому берётся из ФАКТА хода, а не из текста: человек спросил о своих
материалах или разговорах (вид даёт арбитр), к ответу не пришло ни одной записи
НИ ОДНОЙ дорогой, инструменты не вызывались — и ответ всё равно длинный и
утвердительный.

Границы узкие намеренно: предупреждение не по делу обесценивает те, что по делу,
и владелец дважды просил убрать именно такое. Замерено на живых ходах с
проставленным видом: новое предупреждение сработало бы ровно один раз — на том
самом случае.
"""

from __future__ import annotations

import asyncio

import pytest

from friday.agent_runtime import AgentRuntime, _grounding_warning
from friday.permissions import ActorContext

LONG = (
    "Судя по контексту, самым первым сообщением в этой сессии была фраза «Хм, ну вот ты "
    "например работаешь с NVFP4, чем удивишь после этого». Всё, что было до этого, "
    "относится к предыдущим раундам или к самому началу диалога, который уже ушёл в "
    "историю текущей ветки."
)


def test_an_ungrounded_answer_about_his_own_is_flagged() -> None:
    """Мутация: снять эту ветку — тест краснеет, ответ снова уходит без оговорки."""
    warning = _grounding_warning(LONG, None, asked_about_his_own=True, nothing_arrived=True)

    assert warning, "ответ без единой записи ушёл человеку без предупреждения"
    assert "не нашлось ни одной вашей записи" in warning
    assert "инструменты не вызывались" in warning


def test_a_turn_with_data_is_not_flagged() -> None:
    """Обратная сторона: приехала хоть одна запись — предупреждать не о чем."""
    assert _grounding_warning(LONG, None, asked_about_his_own=True, nothing_arrived=False) == ""


def test_a_question_about_the_world_is_not_flagged() -> None:
    """Про погоду и курс валют своих записей и не бывает.

    Ровно эта пометка появлялась раньше под каждым ответом о внешнем мире, и
    владелец дважды просил её убрать. Он прав: предупреждение, которое всегда
    некстати, перестают читать.
    """
    assert _grounding_warning(LONG, None, asked_about_his_own=False, nothing_arrived=True) == ""


def test_an_honest_empty_answer_is_not_flagged() -> None:
    """Ответ сам сказал, что ничего не нашлось, — предупреждать не о чем.

    Иначе система дважды говорит одно и то же: сверху оговорка, снизу признание.
    """
    honest = (
        "В вашем архиве по этому вопросу ничего не нашлось: ни записей, ни документов, "
        "ни упоминаний в переписке. Могу поискать иначе, если подскажете ключевые слова "
        "или период, за который стоит смотреть — иногда помогает название файла."
    )

    assert _grounding_warning(honest, None, asked_about_his_own=True, nothing_arrived=True) == ""


def test_a_short_answer_is_not_flagged() -> None:
    """Короткая реплика утверждением не является, и оговорка была бы длиннее её."""
    assert _grounding_warning("Не помню такого.", None, asked_about_his_own=True, nothing_arrived=True) == ""


def test_the_older_warnings_still_win_when_they_apply() -> None:
    """Ветка о пересказе стоит РАНЬШЕ и говорит точнее — она и должна отвечать.

    Порядок здесь — часть смысла: у пересказа прежних ответов свой текст, и
    заменять его общим было бы потерей.
    """
    retold = (
        "Иванов Иван Иванович (источник вне текущей выборки) — начальник отдела "
        "(источник вне текущей выборки), назначен в марте (источник вне текущей выборки). "
        "Дополнительных сведений в этом ответе нет, всё перечисленное приведено выше."
    )

    warning = _grounding_warning(retold, None, asked_about_his_own=True, nothing_arrived=True)

    assert "пересказ прежних ответов" in warning


@pytest.mark.parametrize(
    "admission",
    [
        "В архиве нет таких документов",
        "Ничего не нашлось по этому запросу",
        "Мне не удалось найти подходящих записей",
        "Поиск ничего не дал",
    ],
)
def test_every_form_of_admission_counts(admission: str) -> None:
    """Признание бывает разным по форме, а смысл один."""
    body = admission + ". " + "Могу посмотреть иначе, если уточните период или название. " * 3

    assert _grounding_warning(body, None, asked_about_his_own=True, nothing_arrived=True) == ""


class _LLM:
    """Подставная модель: отвечает длинно и уверенно, ничего не ища.

    Ровно то поведение, которое и наблюдалось: вопрос про архив, инструменты не
    зовутся, ответ построен на окне контекста.
    """

    enabled = True
    total_budget_sec = 5.0

    def __init__(self, kind: str) -> None:
        self.kind = kind

    async def chat(self, messages, tools=None, **kwargs):  # noqa: ANN001, ARG002
        asked = " ".join(str(m.get("content") or "") for m in messages)
        if "РАЗГОВОР или ЗАПРОС" in asked:
            return {"content": "ЗАПРОС"}
        if '"вид": "интернет' in asked:
            return {"content": f'{{"вид": "{self.kind}", "запрос": "", "кто": "", "дни": []}}'}
        if '"запомнить|забыть|ничего"' in asked:
            return {"content": '{"действие": "ничего", "правило": "", "прежнее": 0, "остаток": ""}'}
        return {"content": LONG}


def _warning_of_a_real_turn(settings, storage, kind: str) -> str:
    storage.ensure_user("alice")
    agent = AgentRuntime(settings, storage)
    agent.llm = _LLM(kind)
    actor = ActorContext(user_id="alice", preset_key="user", source="test")

    answer = asyncio.run(
        agent.chat(
            "alice",
            "Какие сообщения были в самом начале разговора с пользователем RF?",
            actor=actor,
            enable_tools=False,
        )
    )
    return str(answer.get("grounding_warning") or "")


def test_the_guard_is_wired_into_a_real_turn(settings, storage) -> None:
    """Проверяется не механизм, а то, что он ПОДКЛЮЧЁН.

    Мутации «признак берётся не у арбитра» и «пустота считается по одной дороге»
    переживали проверку самой функции: тесты выше зовут `_grounding_warning`
    напрямую и о месте вызова ничего не знают. На этом проекте такое уже ловилось
    трижды — зелёный юнит-тест не доказывает, что продакшен зовёт его верно.
    """
    assert _warning_of_a_real_turn(settings, storage, "архив"), (
        "на настоящем ходу предупреждение не появилось"
    )


def test_a_worldly_question_also_says_it_never_looked(settings, storage) -> None:
    """Про внешний мир оговорка ТОЖЕ нужна — но своя, а не про архив.

    Прежняя редакция требовала здесь пустоты, и это было верно, пока речь шла о
    пометке «ответ не опирается на вашу базу»: под вопросом о курсе доллара она
    не по делу, и владелец дважды просил её убрать.

    Живая переписка владельца 2026-08-04 показала вторую половину: «где в Донецке
    есть RPI5?» → «давай» → ответ с магазином, статусом «в наличии» и ценой в
    гривнах, при `tools_used=[]` и `verification=skipped`. Наличие и цена — не
    мнение: их либо смотрят, либо выдумывают. Поэтому у вопроса о мире теперь
    свой текст — про то, что в интернет не ходили, — и он появляется ровно тогда,
    когда не пришло ничего ни одной дорогой.
    """
    warning = _warning_of_a_real_turn(settings, storage, "интернет")

    assert "в интернет" in warning.casefold(), f"выдумка о внешнем мире прошла молча: {warning!r}"
    assert "вашей записи" not in warning, "вернулась пометка про архив, которую владелец просил убрать"


def test_data_by_another_road_silences_the_guard(settings, storage, monkeypatch) -> None:
    """Пустота считается по ВСЕМ дорогам, а не по одной.

    Ровно этот промах владелец уже ловил: ответ сказал «это тоже проект из твоей
    базы» и получил обвинение во лжи, хотя проект приехал полем профиля — мимо
    поиска по знаниям. Ворота на одной дороге не охраняют ничего, и обратное тоже
    верно: одна закрытая дорога не доказывает, что не приехало НИЧЕГО.

    Здесь данные приходят той самой третьей дорогой — моделью пользователя.
    Записей знаний ноль, сущностей ноль, инструменты не звались, но человеку есть
    на что опереться, и оговорка была бы ложным обвинением.
    """
    monkeypatch.setattr(
        AgentRuntime,
        "_user_model_payload",
        lambda self, user_id: {
            "people": ["RF"],
            "projects": [],
            "interests": [],
            "recent_30d": 2,
        },
    )

    assert _warning_of_a_real_turn(settings, storage, "архив") == "", (
        "оговорка поставлена, хотя данные приехали моделью пользователя"
    )
