"""Системный текст не должен обещать модели инструментов, которых у неё нет.

Он говорил: «Используй инструменты, когда они добавляют проверяемую ценность:
актуальные внешние факты, файлы, вычисления или действие». Из четырёх названных
категорий две не существуют:

* инструмента для ФАЙЛОВ нет вовсе;
* ВЫЧИСЛЕНИЯ — это `code_run`, и он недостижим дважды: способность `code.run`
  объявлена с пустым набором пресетов (`presets=()`), то есть не выдана НИ ОДНОМУ,
  и вдобавок на этой установке выключена настройкой.

Модель, которой сказали «у тебя есть вычисления», либо ищет несуществующий инструмент,
либо отвечает числом, взятым из воздуха. Список доступных инструментов и так
передаётся отдельно — перечислять категории в тексте значит дублировать источник
истины и расходиться с ним.
"""

from __future__ import annotations

from jericho.agent_runtime import SYSTEM_PROMPT
from jericho.permissions import CORE_CAPABILITIES


def test_the_prompt_does_not_enumerate_tool_categories():
    """Перечень категорий разошёлся с действительностью и разойдётся снова."""
    assert "файлы, вычисления" not in SYSTEM_PROMPT
    assert "Список доступных тебе инструментов передан отдельно" in SYSTEM_PROMPT


def test_code_execution_is_granted_to_no_preset():
    """Проба фиксирует ФАКТ, на котором стоит правка выше.

    Если способность когда-нибудь выдадут пресету, этот тест упадёт — и тогда стоит
    заново решить, не вернуть ли упоминание вычислений в текст. Именно так: сначала
    факт, потом обещание, а не наоборот.
    """
    code_run = next(item for item in CORE_CAPABILITIES if item.security_id == "code.run")
    assert code_run.default_presets == (), (
        "code.run кому-то выдан — перечитайте системный текст: он снова может обещать вычисления"
    )


def test_a_new_question_is_a_reason_to_search_again():
    """Прежняя формулировка отговаривала от единственного пути в архив.

    «Не вызывай повторный поиск по памяти без причины» вместе с тем, что контекст
    собран по ПОСЛЕДНЕМУ вопросу, читается как «не ищи». В аудите живой базы 2860
    записей и ни одной `tool.invoke` за 15 диалогов.
    """
    assert "новый вопрос о содержимом архива — это причина" in SYSTEM_PROMPT
