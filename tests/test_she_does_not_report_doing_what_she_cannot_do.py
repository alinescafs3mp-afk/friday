def test_the_refusal_says_both_halves() -> None:
    """Отказ без «что могу» человеку бесполезен: он спросит то же другими словами."""

    assert "не могу" in _CANNOT_ACT_OUTSIDE.casefold()
    assert "могу" in _CANNOT_ACT_OUTSIDE.casefold().split("не могу", 1)[1]
    assert "пошаговый план" in _CANNOT_ACT_OUTSIDE.casefold()
