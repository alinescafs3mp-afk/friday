"""Номер рядом с названием — не часть названия.

Правило «город + до трёх слов» ищет слова через `\\s+`, а `\\s` перешагивает
перевод строки. В анкете за названием города идёт следующая строка, и её начало
прилипало к имени:

    4. Место рождения: | Город Волгоград
    17. Гражданство (приобретённое, когда…)

— так в графе владельца завелись «Волгоград 17», «Самара 17», «Ханты-Мансийск 17»
и «Тюмень 89224794862» (это телефон). Двадцать узлов-двойников настоящих городов,
и на них же пришлись обе ошибки в замере точности падежного сопоставления имён.

Номер дома, индекс, телефон и номер пункта анкеты стоят РЯДОМ с названием, но
частью названия не являются. Проверено на 200 документах живого корпуса: пропали
ровно шесть имён, все шесть — с прилипшим числом.
"""

from __future__ import annotations

from friday.ingestion._base import _extract_entities


def _names(text: str) -> set[str]:
    return {str(item["name"]) for item in _extract_entities(text)}


def test_the_next_form_field_number_does_not_join_the_city():
    text = "4. Место рождения: | Город Волгоград\n17. Гражданство (приобретённое, когда)\n"
    names = _names(text)
    assert "Волгоград" in names
    assert "Волгоград 17" not in names


def test_a_phone_number_on_the_next_line_does_not_join_the_city():
    text = "Место жительства | город Тюмень\n89224794862\n"
    names = _names(text)
    assert "Тюмень" in names
    assert not any(name.startswith("Тюмень 8") for name in names)


def test_a_house_number_does_not_join_the_city():
    text = "5. Адрес места жительства | Город Волжский 14\n"
    assert "Волжский 14" not in _names(text)


def test_a_letter_bearing_code_is_still_a_name():
    """Запрет узкий: он про ЧИСТОЕ число, а не про коды с цифрами.

    «ГПТУ 26» теряет хвост, но «АВ-690234» и «RTX 4090» остаются именами — иначе
    правка выкинула бы обозначения техники и документов вместе с мусором.
    """
    assert "RTX4090" in _names("проект RTX4090 закрыт")
    assert "Альфа-2" in _names("проект Альфа-2 закрыт")
    # Буквенная аббревиатура остаётся частью имени, отваливается только число.
    assert "Белово ГПТУ" in _names("город Белово ГПТУ 26")
