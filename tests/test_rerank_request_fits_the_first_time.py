"""Оценка размера запроса к переранжировщику не должна быть оптимистичной.

Клиент умеет делить слишком большой запрос пополам — и по своей оценке заранее, и
по отказу сервера. Второй путь стоит дорого: полный круг по сети в тот момент,
когда человек ждёт ответа, и только потом деление. В живом журнале таких кругов
было 212 за час.

Причина — константа `_CHARS_PER_TOKEN = 2.3`, замеренная на гладкой прозе. Боевой
корпус здесь другой: расчётные листки и таблицы, где цифры и разметка
токенизируются дороже слов. Замер на НАСТОЯЩИХ документах архива (по 4000 знаков):

    8 документов = 32 000 знаков → проходит
   10 документов = 40 000 знаков → «Tokenized request exceeds 16384 tokens»

то есть не более ~2.0 знака на токен.
"""

from __future__ import annotations

from friday.retrieval._rerank_backend import (
    _CHARS_PER_TOKEN,
    _PAIR_OVERHEAD_TOKENS,
    _REQUEST_MAX_TOKENS,
    DOCUMENT_CHARS,
    _estimated_tokens,
)

# Предел службы `qwen3-reranker-0.6b`, названный ею самой в тексте отказа.
SERVICE_LIMIT_TOKENS = 16_384


def test_the_estimate_is_not_optimistic_about_cyrillic():
    """Мутация: вернуть 2.3 — тест краснеет.

    Проверяется само число, потому что вернуть «как было» проще всего именно не
    глядя: на прозе 2.3 верно, и ошибка проявляется только на корпусе владельца.
    """
    assert _CHARS_PER_TOKEN <= 2.0, (
        f"{_CHARS_PER_TOKEN} знака на токен — на настоящих документах архива замерено "
        "не более 2.0, и завышенная оценка стоит провального круга по сети"
    )


def test_the_batch_that_the_service_refused_is_split_before_sending():
    """Десять документов по 4000 знаков делятся ДО отправки.

    Ровно этот пакет служба отвергла в живом замере; при прежней константе оценка
    считала его проходящим.
    """
    documents = ["я" * DOCUMENT_CHARS] * 10
    estimate = _estimated_tokens("сколько начислено за октябрь 2025", documents)
    assert estimate > _REQUEST_MAX_TOKENS, (
        f"оценка {estimate:.0f} токенов не превысила порог {_REQUEST_MAX_TOKENS} — "
        "пакет уйдёт целиком и вернётся отказом"
    )


def test_a_batch_that_fits_is_not_split_for_nothing():
    """Обратная сторона: маленький пакет не должен дробиться зря.

    Каждое лишнее деление — лишний запрос. Порог обязан разделять два случая, а не
    просто быть строгим.
    """
    documents = ["я" * DOCUMENT_CHARS] * 3
    estimate = _estimated_tokens("сколько начислено за октябрь 2025", documents)
    assert estimate <= _REQUEST_MAX_TOKENS, (
        f"оценка {estimate:.0f} токенов дробит пакет из трёх документов — это лишний круг"
    )


def test_the_estimate_stays_under_what_the_service_actually_accepts():
    """Порог клиента ниже предела службы, и запас реальный, а не на глаз.

    `_REQUEST_MAX_TOKENS` — не то же самое, что предел службы: между ними должен
    оставаться зазор на неточность оценки, иначе «влезает по нашим расчётам»
    регулярно означало бы «отказ по её расчётам».
    """
    assert _REQUEST_MAX_TOKENS < SERVICE_LIMIT_TOKENS
    # Зазор ЗАМЕРЕННЫЙ, а не назначенный: 15 000 против 16 384 — это 8.4%, и на
    # боевом прогоне (78 запросов с переранжированием) отказов не осталось ни
    # одного. Требовать здесь круглые «25% запаса» значило бы придумать критерий
    # вместо проверки — первая редакция теста так и делала и падала на ровном месте.
    headroom = (SERVICE_LIMIT_TOKENS - _REQUEST_MAX_TOKENS) / SERVICE_LIMIT_TOKENS
    assert headroom >= 0.05, f"запас всего {headroom:.1%} — промах оценки снова станет отказом службы"
    assert _PAIR_OVERHEAD_TOKENS > 0, "накладные на пару учитываются: вопрос входит в каждую"
