"""Надзор не отрицает того, чего не проверял.

Найдено ревью уязвимых участков 2026-08-04, уточнено скептиком и подтверждено
замером на живой базе.

ЧТО ЗАМЕРЕНО: все 3295 документов лежат под ОДНИМ идентификатором (архив общий), а
признака автора у них нет вовсе — система не записывает, кто загрузил файл. Значит
вопрос «что Иван присылал» сегодня неразрешим в принципе: поиск по человеку даёт
ноль ВСЕГДА, а не потому, что человек ничего не присылал.

ЧТО ПРИ ЭТОМ ДОХОДИЛО ДО МОДЕЛИ: готовая фраза «за этот период человек ничего не
писал и не присылал». То есть уверенное отрицание про живого человека, на котором
строится кадровое суждение, — и построено оно на вопросе, которого никто не
задавал.

Правка узкая и честная: ход называет, ЧЕГО именно нет. Переписки за период не
нашлось — это правда, её ищут по человеку. По загруженным материалам ответа нет
вообще, и так и сказано.

Полный учёт автора загрузки — отдельная работа: нужна миграция и решение, что
делать с уже накопленными документами. Она не может быть сделана молча ночью, а
ложь в ответе — может и должна быть убрана сразу.
"""

from __future__ import annotations

from datetime import UTC

from friday.execution_kernel import _person_answer_for_llm


def _answer(**over):
    base = {"person": {"display_name": "Иван"}, "messages": [], "items": [], "summary": {}}
    base.update(over)
    return base


def _trim(answer):
    return _person_answer_for_llm(answer, zone=UTC)


def test_an_empty_window_does_not_claim_he_sent_nothing() -> None:
    """Мутация: вернуть прежнюю фразу — тест краснеет."""
    trimmed = _trim(_answer())

    joined = str(trimmed)
    assert "ничего не писал и не присылал" not in joined, (
        "надзор снова отрицает то, чего не проверял"
    )
    # Формулировка сменилась 2026-08-04 вместе с появлением отметки автора: вместо
    # общего «материалы не разделены по людям» ход называет ЧИСЛО безымянных
    # загрузок за окно. Здесь поля нет вовсе — значит никто не считал, и берётся
    # осторожная ветка. «Не считали» и «посчитали, вышел ноль» — разные вещи, и
    # умолчание обязано толковаться в сторону оговорки: речь о живом человеке.
    assert "без отметки о том, кто их загрузил" in joined, "модели не сказано, почему ответа нет"


def test_the_model_is_told_the_answer_is_unknown() -> None:
    """Модель получает ФАКТ, из которого отрицание не следует.

    Без него она видит пустоту и заполняет её сама — этот класс на проекте
    замерен многократно, и здесь цена ошибки особенно велика: речь о живом
    человеке.

    Прежняя редакция требовала дословного «Не отвечай, что человек ничего не
    присылал» — то есть прибивала к тесту ПРИКАЗ, положенный в данные
    инструмента. Модель не отличает данные от инструкции и такие строки
    пересказывает человеку целиком; сказано должно быть то же, но фактом.
    """
    trimmed = str(_trim(_answer()))

    assert "могли быть среди них" in trimmed, "не сказано, что загрузки человека могли быть среди безымянных"
    assert "по загрузкам данных нет" in trimmed, "неизвестность не названа неизвестностью"
    for order in ("не отвечай", "скажи, что"):
        assert order not in trimmed.casefold(), f"служебная строка написана как приказ: {trimmed!r}"


def test_messages_found_means_no_disclaimer() -> None:
    """Обратная сторона: когда переписка нашлась, оговорка не нужна.

    Предупреждение, которое всегда некстати, обесценивает те, что по делу.
    """
    trimmed = _trim(_answer(messages=[{"at": "2026-08-01T10:00:00+00:00", "text": "привет"}]))

    assert "без отметки о том, кто их загрузил" not in str(trimmed)


def test_files_found_are_reported_as_before() -> None:
    """Если загрузки видны — они и показываются, поведение не изменилось."""
    trimmed = _trim(
        _answer(
            items=[{"at": "2026-08-01T10:00:00+00:00", "title": "акт.pdf"}],
            summary={"arrivals": 1},
        )
    )

    assert trimmed.get("присылал файлов") == 1
    assert "не разделены по людям" not in str(trimmed)


def test_when_every_upload_is_signed_the_answer_is_plain() -> None:
    """Посчитали и вышел ноль — отрицание становится законным.

    Оговорка, которая не снимается никогда, обесценивает себя: её перестают читать.
    Число безымянных загрузок само стареет в нужную сторону — по мере того как новые
    документы приходят с отметкой автора, в свежем окне их не остаётся, и ход
    отвечает прямо, без единой правки в коде.
    """
    trimmed = _trim(_answer(arrivals_without_an_author=0))

    joined = str(trimmed)
    assert "материалов от него не поступало" in joined, "ответ по-прежнему уклончив"
    assert "Не отвечай" not in joined, "модели запрещают то, что она вправе сказать"
