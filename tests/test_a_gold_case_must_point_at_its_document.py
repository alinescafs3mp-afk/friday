"""Вопрос эталона должен указывать на СВОЮ заметку, а не на класс документов.

Разбор 2026-08-03. Из 78 эталонов поиска не находились 30, и 27 из них оказались
одним классом — расчёты денежного довольствия за месяц. Причина сначала выглядела
как слабость поиска, а оказалась изъяном НАБОРА: вопрос «расчёт зарплаты
контрактника за декабрь 2025» не называет человека, а таких расчётов в архиве по
одному на каждого — 34 документа содержат «начисления» и «12.2025» одновременно.
Эталон при этом ждёт один конкретный.

Генератор эталонов знал только половину правила. Он требовал, чтобы вопрос НЕ
пересказывал заметку своими словами (иначе набор мерит совпадение слов, а не
поиск), и никогда не проверял обратное — отличает ли вопрос эту заметку от
остальных полутора тысяч. Обе половины нужны: без первой набор слишком лёгкий,
без второй — требует невозможного и молча занижает число, по которому судят.

Почему предупреждение, а не отказ. Замерено на архиве владельца: без приметы
оказались 40 эталонов из 78, а не находятся 30. Значит десять случаев поиск берёт
и БЕЗ буквального совпадения — ровно те, ради которых существует плотный канал.
Браковать их значило бы выбросить самые ценные проверки.

Отличить «трудный, но справедливый» от «безнадёжного» счётчиком нельзя: разница в
том, названо ли в вопросе что-то конкретное — имя, номер, — а это вопрос смысла.
Решает человек, он и так утверждает каждое предложение.
"""

from __future__ import annotations

from friday.eval_bootstrap import (
    MAX_DOCUMENTS_WITH_THE_WORD,
    content_tokens,
    corpus_stems,
    pointing_words,
)


def test_a_rare_word_points_at_the_document() -> None:
    """«Поверка» — примета, если поверок в архиве единицы."""
    corpus = corpus_stems(["график поверки весов", "устав караульной службы", "приказ о переводе"])
    document = content_tokens("график поверки весов на 2026 год")

    assert pointing_words("что там по поверке весов", document, corpus)


def test_a_common_word_points_at_nothing() -> None:
    """«Зарплата» и «декабрь» приметами не являются: их сотни.

    Проверяется на архиве, где нужное слово встречается ЧАЩЕ порога: сам порог и
    решает, а не длина слова.
    """
    many = [f"расчёт начисления декабрь 2025 оклад сотрудник {index}" for index in range(30)]
    corpus = corpus_stems(many)
    document = content_tokens(many[0])

    assert pointing_words("расчёт начисления декабрь", document, corpus) == []


def test_a_word_absent_from_the_document_is_not_a_pointer() -> None:
    """Главный случай: вопрос СЛОВАМИ не пересекается со своим документом.

    «Расчёт зарплаты контрактника» против документа, где написано «начисления»,
    «оклад», «военнослужащий». Ни одна примета не совпадает — вопрос про класс.
    """
    corpus = corpus_stems(["начисления оклад военнослужащий 12.2025", "устав"])
    document = content_tokens("начисления оклад военнослужащий 12.2025")

    assert pointing_words("расчёт зарплаты контрактника", document, corpus) == []


def test_the_threshold_is_the_page_of_results() -> None:
    """Порог взят вплотную к размеру выдачи, а не с запасом."""
    assert MAX_DOCUMENTS_WITH_THE_WORD == 10


def test_the_generator_asks_for_a_distinguishing_question() -> None:
    """Модель просят об однозначности прямо, а не надеются на неё."""
    from friday.eval_bootstrap import _PROMPT

    assert "однозначно" in _PROMPT
    assert "имя, номер, дату" in _PROMPT
    assert "НЕ повторяй слова из заметки" in _PROMPT, "первая половина правила потерялась"


def test_a_question_without_a_pointer_is_flagged_not_rejected() -> None:
    """Мутация: снова браковать такие вопросы — тест краснеет.

    Десять эталонов из архива владельца находятся, не имея ни одной приметы.
    Отказ выбросил бы их вместе с безнадёжными.
    """
    import inspect

    from friday.eval_bootstrap import propose_cases

    source = inspect.getsource(propose_cases)
    marker = source.index("pointing_words(")
    guard = source[marker : marker + 1400]
    assert "proposal.accepted = False" not in guard, "предупреждение снова стало отказом"
    assert "proposal.reason" in guard, "человеку ничего не сказано"


def test_the_stems_are_computed_once() -> None:
    """Прибор, считающий весь архив на каждый вопрос, не доживает до ответа.

    Первая редакция звала `content_tokens` внутри проверки — 78 вопросов на 1559
    документов. Прогон пришлось убить.
    """
    computed = corpus_stems(["первый документ", "второй документ"])

    assert all(isinstance(item, set) for item in computed)
    assert "документ" in str(computed)
