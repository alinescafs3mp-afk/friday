def _backup(args: argparse.Namespace) -> int:
    from jericho.backup_mirror import mirror_backups
    from jericho.config import ensure_runtime_dirs, load_settings
    from jericho.storage import init_storage

    settings = load_settings()
    ensure_runtime_dirs(settings)
    storage = init_storage(settings)
    try:
        result = storage.create_backup(label=args.label)
    finally:
        storage.close()
    mirror = mirror_backups(settings)
    _json_print({**result, "mirror": mirror})
    if not mirror.get("enabled"):
        print(
            "⚠ Зеркалирование выключено: копия лежит на том же диске. "
            "Настройте JERICHO_BACKUP_MIRROR_DIR (внешний диск/синхронизируемый каталог).",
            file=sys.stderr,
        )
    return 0


def _backup_keygen(args: argparse.Namespace) -> int:
    """Generate a backup-encryption key file (referenced by the env setting)."""
    from jericho.config import load_settings

    settings = load_settings()
    target = Path(args.out).expanduser() if args.out else settings.backup_encryption_key_file
    if target is None:
        print(
            "Укажите --out или задайте JERICHO_BACKUP_ENCRYPTION_KEY_FILE в .env.local",
            file=sys.stderr,
        )
        return 2
    if target.exists() and not args.force:
        print(f"Не перезаписываю существующий ключ: {target} (используйте --force)")
        return 2
    _write_private_text_atomic(target, secrets.token_hex(32) + "\n")
    print(f"Ключ шифрования бэкапов записан: {target} (права 600)")
    print("Храните копию ключа ОТДЕЛЬНО от зеркала: без ключа .enc-копии невосстановимы.")
    return 0


def _decrypt_backup(args: argparse.Namespace) -> int:
    from jericho.backup_mirror import decrypt_file
    from jericho.config import load_settings

    settings = load_settings()
    key_file = Path(args.key).expanduser() if args.key else settings.backup_encryption_key_file
    if key_file is None:
        print("Укажите --key или задайте JERICHO_BACKUP_ENCRYPTION_KEY_FILE", file=sys.stderr)
        return 2
    source = Path(args.filename).expanduser()
    destination = (
        Path(args.out).expanduser() if args.out else source.with_name(source.name.removesuffix(".enc"))
    )
    if destination.exists():
        print(f"Не перезаписываю существующий файл: {destination}", file=sys.stderr)
        return 2
    decrypt_file(source, destination, key_file)
    print(f"Расшифровано: {destination}")
    print("Дальше: `jericho verify-backup` рядом с манифестом или `jericho restore-backup`.")
    return 0


def _verify_backup(args: argparse.Namespace) -> int:
    from jericho.config import ensure_runtime_dirs, load_settings
    from jericho.storage import init_storage

    settings = load_settings()
    ensure_runtime_dirs(settings)
    storage = init_storage(settings)
    try:
        filename = args.filename
        if not filename:
            backups = storage.list_backups()
            if not backups:
                print("Резервных копий не найдено.", file=sys.stderr)
                return 2
            filename = str(backups[0]["database"])
        result = storage.verify_backup(filename)
    finally:
        storage.close()
    _json_print(result)
    return 0 if result.get("ok") else 1


def _restore_backup(args: argparse.Namespace) -> int:
    """Restore one database backup while the backend process role is exclusive."""

    if not args.yes:
        print(
            "Восстановление заменит активную SQLite-базу. Повторите команду с --yes после "
            "остановки backend и Telegram bridge.",
            file=sys.stderr,
        )
        return 2

    from jericho.config import ensure_runtime_dirs, load_settings
    from jericho.diagnostics.runtime_lease import ProcessLease
    from jericho.storage import init_storage

    settings = load_settings()
    ensure_runtime_dirs(settings)
    with ProcessLease(settings.state_dir / "backend.lock", protocol="jericho.backend.v1"):
        storage = init_storage(settings)
        try:
            filename = args.filename
            if not filename:
                backups = storage.list_backups()
                if not backups:
                    print("Резервных копий не найдено.", file=sys.stderr)
                    return 2
                filename = str(backups[0]["database"])
            result = storage.restore_backup(
                filename,
                safety_label=f"pre-restore-{Path(filename).stem}",
            )
        finally:
            storage.close()
    _json_print(result)
    print(
        "Важно: восстановлена только SQLite-база; raw files, memory vault, веса модели и "
        "локальная конфигурация не изменялись.",
        file=sys.stderr,
    )
    return 0


