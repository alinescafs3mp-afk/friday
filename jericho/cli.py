def _up(args: argparse.Namespace) -> int:
    """One-command launch: validate config, then supervise backend (+bridge)."""
    import sys

    from jericho.config import ensure_runtime_dirs, load_settings, validate_settings
    from jericho.diagnostics.runtime_lease import inspect_process_lease
    from jericho.supervisor import ChildSpec, Supervisor

    settings = load_settings()
    ensure_runtime_dirs(settings)
    problems = validate_settings(settings, production=not settings.is_loopback_bind)
    errors = [item for item in problems if not item.startswith("warning:")]
    for problem in problems:
        print(("⚠ " if problem.startswith("warning:") else "✖ ") + problem)
    if errors:
        print("Конфигурация не готова — исправьте ошибки выше (.env.local).")
        return 2

    backend_lease = inspect_process_lease(settings.state_dir / "backend.lock", protocol="jericho.backend.v1")
    if backend_lease.get("active"):
        print(f"Backend уже запущен (pid {backend_lease.get('pid')}). Второй не нужен.")
        return 2

    env_file = os.environ.get("JERICHO_ENV_FILE", "")
    base_argv = [sys.executable, "-m", "jericho.cli"]
    if env_file:
        base_argv += ["--env-file", env_file]

    children = [
        ChildSpec(
            name="backend",
            argv=[*base_argv, "server"],
            log_path=settings.log_dir / "backend.log",
            cwd=settings.home,
        )
    ]
    bot_token = os.environ.get("JERICHO_TELEGRAM_BOT_TOKEN", "").strip()
    if args.no_bridge:
        print("Мост Telegram пропущен (--no-bridge).")
    elif not bot_token:
        print("Мост Telegram пропущен: JERICHO_TELEGRAM_BOT_TOKEN не задан.")
    else:
        children.append(
            ChildSpec(
                name="telegram-bridge",
                argv=[*base_argv, "telegram-bridge"],
                log_path=settings.log_dir / "telegram-bridge.log",
                cwd=settings.home,
            )
        )

    print(f"Запускаю {', '.join(child.name for child in children)}; логи в {settings.log_dir}")
    print("Остановка: Ctrl+C (дети получают SIGTERM и завершаются штатно).")
    return Supervisor(children).run()


_SYSTEMD_UNIT_TEMPLATE = """[Unit]
Description=Jericho {role}
After=network-online.target{after_extra}

[Service]
Type=simple
ExecStart={exec_start}
Restart=on-failure
RestartSec=5
{environment}WorkingDirectory={workdir}

[Install]
WantedBy=default.target
"""


def _install_services(args: argparse.Namespace) -> int:
    """Generate systemd --user units; printing, not enabling — the user decides."""
    import sys

    from jericho.config import load_settings

    settings = load_settings()
    target_dir = Path(args.dir or Path.home() / ".config" / "systemd" / "user").expanduser()
    target_dir.mkdir(parents=True, exist_ok=True)

    env_file = os.environ.get("JERICHO_ENV_FILE", "")
    env_arg = f" --env-file {env_file}" if env_file else ""
    environment = f"Environment=JERICHO_HOME={settings.home}\n"

    units: list[tuple[str, str]] = []
    units.append(
        (
            "jericho-backend.service",
            _SYSTEMD_UNIT_TEMPLATE.format(
                role="backend (API + Admin UI)",
                after_extra="",
                exec_start=f"{sys.executable} -m jericho.cli{env_arg} server",
                environment=environment,
                workdir=settings.home,
            ),
        )
    )
    units.append(
        (
            "jericho-bridge.service",
            _SYSTEMD_UNIT_TEMPLATE.format(
                role="Telegram bridge",
                after_extra=" jericho-backend.service",
                exec_start=f"{sys.executable} -m jericho.cli{env_arg} telegram-bridge",
                environment=environment,
                workdir=settings.home,
            ),
        )
    )
    for name, content in units:
        (target_dir / name).write_text(content, encoding="utf-8")
        print(f"Записан {target_dir / name}")
    if sys.executable.startswith(("/tmp/", "/var/tmp/")):
        print(
            "⚠ ExecStart указывает на временный Python-интерпретатор. Установите Jericho в "
            "постоянный venv и перегенерируйте юниты перед enable."
        )
    print()
    print("Дальше (мост включайте только с настроенным JERICHO_TELEGRAM_BOT_TOKEN):")
    print("  systemctl --user daemon-reload")
    print("  systemctl --user enable --now jericho-backend")
    print("  systemctl --user enable --now jericho-bridge")
    print("  loginctl enable-linger $USER   # чтобы сервисы жили без активной сессии")
    return 0


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()
    if args.env_file:
        os.environ["JERICHO_ENV_FILE"] = str(Path(args.env_file).expanduser().resolve())
    # Load local secrets before installing formatters, otherwise early startup
    # failures could render credential-bearing values without exact redaction.
    from jericho.config import load_local_env_file

    load_local_env_file()
    configure_logging(args.log_level)
    try:
        code = int(args.handler(args) or 0)
    except (ValueError, RuntimeError, FileNotFoundError) as exc:
        logging.getLogger(__name__).error("%s", exc)
        code = 2
    raise SystemExit(code)


if __name__ == "__main__":
    main()
