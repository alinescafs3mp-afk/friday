"""Переранжирование выдачи локальной моделью — ЗАМЕРЕНО И НЕ ОПРАВДАЛОСЬ.

Механизм оставлен рабочим и выключенным, вместе с числами: он верен по устройству и
может окупиться на другой модели. Сегодняшняя его не тянет, и вот чем это доказано.

ЗАЧЕМ ЗАТЕВАЛОСЬ. Замерено на корпусе владельца (1537 документов, 80 вопросов от
модели, судья с известной базой 12.2% «да» на случайном документе): точность выдачи
ПЛОСКАЯ по глубине — 40.0% в пятёрке, 38.4% в десятке, 40.5% в двадцатке. Документ на
двадцатом месте отвечает примерно так же часто, как на первом. Отбор кандидатов
работает (40% против базы 12.2%), а упорядочивание внутри — нет: ни один канал слияния
не оценивает то, ради чего человек пришёл, — отвечает ли документ на вопрос.

ЧТО ПОКАЗАЛ ЗАМЕР. Потолок был известен заранее: переранжирование десятки поднимает
«есть ответ в пятёрке» с 75.0% максимум до 80.0%, то есть четыре вопроса из восьмидесяти.

    безоговорочная перестановка: первым чаще на +7 и +4 вопроса (две половины),
      но ответы ВЫПАДАЮТ из пятёрки: −6 и −5. MRR 0.547->0.563 и 0.507->0.511.
    подъём не более одного:      +6 и +3 первым, −1 охвата, MRR +0.041 и +0.021.

Выглядело как размен, потом как маленький выигрыш. И то и другое оказалось ложным.

ПОЧЕМУ ЛОЖНЫМ — три замера, каждый опровергает предыдущее объяснение:

1. Через роутер модель отвечает ДВУМЯ токенами за 0.27 с: роутер шлёт
   `enable_thinking: False`, и нынешний рантайм этот флаг соблюдает. Оценка делается
   без рассуждения, и ответы вырожденные — «ни один» или «все десять»: на шести
   вопросах названо 0, 0, 10, 0, 1, 10.
2. Прямым обращением, с рассуждением, — 12.8 с на вопрос и те же вырожденные ответы
   (0, 0, 1, 0, 0, 10). Дело не в рассуждении, а в ПАКЕТНОЙ постановке: судья смотрит
   один документ и отвечает да/нет — он работает; переранжировщик смотрит десять
   сразу — не работает.
3. Выдержки в 800 знаков недостаточно, чтобы судить. На тех же десяти документах
   судья с выдержкой 5000 знаков находит два отвечающих, а с 800 — ни одного, в обеих
   конфигурациях. Длину я выбрал по замеру СКОРОСТИ (400 знаков дороже 800, потому что
   по обрывку модель дольше рассуждает) и не проверил, что она делает с ТОЧНОСТЬЮ.

Отсюда: «+3 вопроса на отложенной половине», о которых сначала было доложено, получены
переранжировщиком, который пропускает настоящие ответы. Это шум, а не выигрыш.

ЧТО СТОИЛО БЫ ПОПРОБОВАТЬ, если возвращаться. Судейская формулировка (один документ —
один вопрос) работает и распараллеливается дёшево: десять одновременных обращений
занимают 0.79 с без рассуждения и 11.6 с с рассуждением против 61 последовательно. То
есть узкое место не в числе обращений, а в связке «рассуждение + длинная выдержка»:
точная конфигурация стоит 15-25 секунд на запрос при потолке выигрыша в четыре вопроса
из восьмидесяти. Для живого поиска это не окупается.

ЧТО ШАГ НЕ ДЕЛАЕТ, если его всё-таки включат:

* Не добавляет кандидатов. На вход приходит уже прошедшее гейт доказательств; вернуть
  можно только перестановку. Иначе шаг стал бы четвёртым обходом review-gate — их в
  этом проекте закрывали трижды.
* Не выбрасывает неназванное — оно уходит вниз. Ошибка модели должна стоить места в
  списке, а не исчезновения.
* Не очищает выдачу на ответ «не отвечает ни один»: это мнение модели, а не решение
  за человека.
* Не роняет поиск: нет ответа, не разобрался JSON, модель недоступна — прежний порядок.
"""

from __future__ import annotations

import json
import logging
import re
from typing import Any, Protocol

LOGGER = logging.getLogger(__name__)

# Длина выдержки. Замерено: 400 знаков дороже 800, потому что по обрывку модель дольше
# рассуждает, а на двадцати фрагментах ещё и упирается в потолок токенов.
EXCERPT_CHARS = 800

_PROMPT = """Вопрос: {question}

Ниже пронумерованные фрагменты документов из личного архива. Оцени каждый: отвечает ли \
он на вопрос — прямо или по существу.

{blocks}

Верни ТОЛЬКО JSON-массив номеров тех фрагментов, которые отвечают на вопрос, от самого \
подходящего к менее подходящему. Если не отвечает ни один — верни пустой массив. \
Без пояснений и без Markdown."""


class SupportsChat(Protocol):
    async def chat(
        self,
        messages: list[dict[str, Any]],
        *,
        temperature: float | None = None,
        max_tokens: int | None = None,
        priority: str = "foreground",
        tools: list[dict[str, Any]] | None = None,
    ) -> dict[str, Any]: ...


def _excerpt(item: dict[str, Any]) -> str:
    """Заголовок плюс начало тела: по одному телу без заголовка модель хуже различает
    однотипные служебные документы, а они тут все однотипные."""
    title = str(item.get("title") or "").strip()
    body = " ".join(str(item.get("content") or "").split())
    head = f"{title}. " if title else ""
    return (head + body)[:EXCERPT_CHARS]


def parse_order(text: str, count: int) -> list[int] | None:
    """Вытащить массив номеров из ответа модели.

    Отдельной функцией, потому что это единственное место, где ответ модели становится
    решением, и оно должно быть проверяемо тестом без сети. Рассуждающая модель кладёт
    монолог перед ответом; годным считается ПОСЛЕДНИЙ массив в тексте, а не первый —
    первый обычно оказывается внутри рассуждения.
    """
    tail = re.sub(r"^.*</think>", "", text or "", flags=re.S)
    matches = re.findall(r"\[[^\[\]]*\]", tail)
    for candidate in reversed(matches):
        try:
            parsed = json.loads(candidate)
        except json.JSONDecodeError:
            continue
        if not isinstance(parsed, list):
            continue
        seen: set[int] = set()
        order: list[int] = []
        for value in parsed:
            if not isinstance(value, int) or isinstance(value, bool):
                continue
            if 0 <= value < count and value not in seen:
                seen.add(value)
                order.append(value)
        return order
    return None


async def rerank(
    llm: SupportsChat,
    query: str,
    items: list[dict[str, Any]],
    *,
    budget_sec: float | None = None,
    max_promoted: int = 0,
) -> list[dict[str, Any]] | None:
    """Переставить `items` по тому, отвечают ли они на `query`. None — оставить как было.

    Возвращается ПЕРЕСТАНОВКА тех же объектов: названные моделью в её порядке, затем
    остальные в прежнем. Ни один объект не теряется — это проверяется тестом, потому
    что потеря выглядела бы как «поиск ничего не нашёл», а не как сбой модели.
    """
    if len(items) < 2:
        return None
    blocks = "\n\n".join(f"[{index}] {_excerpt(item)}" for index, item in enumerate(items))
    try:
        response = await llm.chat(
            [{"role": "user", "content": _PROMPT.format(question=query, blocks=blocks)}],
            temperature=0.0,
            # Столько же, сколько совету по Inbox: замерено, что до JSON рассуждающая
            # модель думает 2516-3616 токенов, а на двадцати фрагментах доходит до 4096.
            max_tokens=4096,
            priority="foreground",
            tools=[],
        )
    except Exception as exc:  # noqa: BLE001
        LOGGER.info("rerank skipped: %s", exc)
        return None

    order = parse_order(str(response.get("content") or ""), len(items))
    if order is None:
        LOGGER.info("rerank skipped: model returned no usable order")
        return None
    if not order:
        # Модель говорит, что не отвечает ни один. Это НЕ повод очистить выдачу:
        # решение о полезности принимает человек, а гейт доказательств уже отработал.
        return None
    # Сколько названного поднимать наверх. Безоговорочная перестановка замерена и
    # оказалась разменом, а не выигрышем: отвечающий становится первым чаще (+7 и +4
    # вопроса на двух половинах), но ответы ВЫПАДАЮТ из видимой пятёрки (−6 и −5),
    # потому что названное с мест 7-9 занимает первые слоты и вытесняет то, что
    # стояло на 3-5 и тоже отвечало. MRR при этом не двигается — в сумме качество не
    # растёт, меняется только распределение.
    #
    # Поэтому подъём ограничивается: первые места достаются названному, но прежний
    # порядок ниже сохраняется. `0` — без ограничения, прежнее поведение.
    limit = len(order) if max_promoted <= 0 else min(max_promoted, len(order))
    promoted = order[:limit]
    chosen = [items[index] for index in promoted]
    rest = [item for index, item in enumerate(items) if index not in set(promoted)]
    return chosen + rest
