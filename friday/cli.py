_TTL_UNITS = {"s": 1, "m": 60, "h": 3600, "d": 86400}


def _parse_ttl_seconds(value: str) -> int:
    """Parse a TTL like '90d', '24h', '30m', '3600s', or bare seconds into seconds."""

    from friday.storage import MAX_API_TOKEN_TTL_SECONDS

    text = value.strip().lower()
    if not text:
        raise ValueError("empty TTL")
    unit = 1
    if text[-1] in _TTL_UNITS:
        unit = _TTL_UNITS[text[-1]]
        text = text[:-1]
    # Strict ASCII digits only: reject signs, spaces, underscores, unicode digits.
    if not (text.isascii() and text.isdigit()):
        raise ValueError(f"invalid TTL: {value!r}")
    seconds = int(text) * unit
    if seconds <= 0 or seconds > MAX_API_TOKEN_TTL_SECONDS:
        raise ValueError(f"TTL out of range: {value!r}")
    return seconds


def _write_private_text_atomic(path: Path, content: str) -> None:
    """Replace a local secret file atomically without following a target symlink."""

    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        raise ValueError(f"Refusing to write configuration through a symlink: {path}")
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.",
        suffix=".tmp",
        dir=path.parent,
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        with suppress(OSError):
            temporary.chmod(0o600)
        os.replace(temporary, path)
        with suppress(OSError):
            path.chmod(0o600)
    finally:
        temporary.unlink(missing_ok=True)


