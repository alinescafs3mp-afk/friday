def _up(args: argparse.Namespace) -> int:
    """One-command launch: validate config, then supervise backend (+bridge)."""
    import sys

    from friday.config import ensure_runtime_dirs, load_settings, validate_settings
    from friday.diagnostics.runtime_lease import inspect_process_lease
    from friday.supervisor import ChildSpec, Supervisor

    settings = load_settings()
    ensure_runtime_dirs(settings)
    problems = validate_settings(settings, production=not settings.is_loopback_bind)
    errors = [item for item in problems if not item.startswith("warning:")]
    for problem in problems:
        print(("⚠ " if problem.startswith("warning:") else "✖ ") + problem)
    if errors:
        print("Конфигурация не готова — исправьте ошибки выше (.env.local).")
        return 2

    backend_lease = inspect_process_lease(settings.state_dir / "backend.lock", protocol="friday.backend.v1")
    if backend_lease.get("active"):
        print(f"Backend уже запущен (pid {backend_lease.get('pid')}). Второй не нужен.")
        return 2

    env_file = config_env("FRIDAY_ENV_FILE", "")
    base_argv = [sys.executable, "-m", "friday.cli"]
    if env_file:
        base_argv += ["--env-file", env_file]

    children = [
        ChildSpec(
            name="backend",
            argv=[*base_argv, "server"],
            log_path=settings.log_dir / "backend.log",
            cwd=settings.home,
        )
    ]
    bot_token = config_env("FRIDAY_TELEGRAM_BOT_TOKEN", "").strip()
    if args.no_bridge:
        print("Мост Telegram пропущен (--no-bridge).")
    elif not bot_token:
        print("Мост Telegram пропущен: FRIDAY_TELEGRAM_BOT_TOKEN не задан.")
    else:
        children.append(
            ChildSpec(
                name="telegram-bridge",
                argv=[*base_argv, "telegram-bridge"],
                log_path=settings.log_dir / "telegram-bridge.log",
                cwd=settings.home,
            )
        )

    print(f"Запускаю {', '.join(child.name for child in children)}; логи в {settings.log_dir}")
    print("Остановка: Ctrl+C (дети получают SIGTERM и завершаются штатно).")
    return Supervisor(
        children,
        log_max_bytes=settings.log_max_bytes,
        log_backups=settings.log_backups,
    ).run()


