def _status(args: argparse.Namespace) -> int:
    from friday.config import load_settings
    from friday.diagnostics import collect_diagnostics

    settings = load_settings()
    result = collect_diagnostics(settings, check_llm_port=args.check_llm, check_secrets=True)
    if args.json:
        _json_print({"version": __version__, **result})
    else:
        db = result["database"]
        backups = result.get("backups", {})
        workers = result.get("workers", {})
        lease = result.get("backend_lease", {})
        print(f"Friday {__version__}")
        print(f"State: {result.get('state', 'unknown')}")
        print(f"Home: {settings.home}")
        print(f"Database: {settings.database_path}")
        print(f"Schema: {db.get('schema_version', 'not initialized')}")
        print(f"Database integrity: {db.get('integrity_check', 'not created')}")
        latest = backups.get("latest") or {}
        if backups.get("verified"):
            print(f"Latest backup: verified · {latest.get('database')} · {latest.get('created_at')}")
        else:
            print(f"Latest backup: {backups.get('state', 'unknown')}")
        backend_state = lease.get("state", "unknown")
        backend_pid = lease.get("pid")
        print(f"Backend lease: {backend_state}{f' · pid {backend_pid}' if backend_pid else ''}")
        from friday.diagnostics.runtime_lease import inspect_process_lease

        bridge_lease = inspect_process_lease(
            settings.state_dir / "telegram-inbox.sqlite3.lock",
            protocol="friday.telegram-bridge.v1",
        )
        bridge_pid = bridge_lease.get("pid")
        print(
            f"Bridge lease: {bridge_lease.get('state', 'unknown')}"
            f"{f' · pid {bridge_pid}' if bridge_pid else ''}"
        )
        bridge_queue = result.get("bridge_queue", {})
        if bridge_queue.get("state") == "present":
            print(
                "Bridge queue: "
                f"{bridge_queue.get('pending', 0)} pending · "
                f"{bridge_queue.get('dead_letter', 0)} dead-letter"
            )
        outbound_pending = db.get("outbound_pending")
        if outbound_pending is not None:
            print(f"Outbound queue: {outbound_pending} pending")
        print(
            "Workers: "
            f"{workers.get('state', 'unknown')} · "
            f"tasks {workers.get('task_count', 0)} · "
            f"healthy {'yes' if workers.get('healthy', True) else 'no'}"
        )
        print(
            f"Model directory: {settings.model_dir} "
            f"({'weights detected' if result['paths']['model'].get('usable_files_detected') else 'empty or missing'})"
        )
        print(f"Configuration: {'OK' if result['ok'] else 'needs attention'}")
        for issue in result.get("configuration_issues", []):
            print(f"  - {issue}")
        if args.check_llm:
            endpoint = result.get("llm_endpoint", {})
            print(f"LLM endpoint: {'reachable' if endpoint.get('reachable') else 'unreachable'}")
        actions = result.get("actions", [])
        if actions:
            print("\nRecommended actions:")
            for action in actions:
                marker = {"error": "!", "warning": "~", "setup": "+"}.get(
                    str(action.get("severity")),
                    "-",
                )
                print(f"  {marker} {action.get('title')}: {action.get('detail')}")
                if action.get("command"):
                    print(f"      {action['command']}")
    return 0 if result.get("state") in {"ready", "attention"} else 1


