def _telegram_backend_url(settings: Any) -> str:
    """Private backend URL whose default follows the server's native TLS mode."""

    # This compares configured bind literals; it does not open a listener. A
    # wildcard bind is reachable from the sibling bridge through loopback.
    host = settings.local_api_client_host
    if ":" in host and not host.startswith("["):
        host = f"[{host}]"
    scheme = "https" if settings.api_tls_enabled else "http"
    configured = config_env("FRIDAY_BACKEND_URL", "").strip()
    return (configured or f"{scheme}://{host}:{settings.api_port}").rstrip("/")


def _run_telegram_bridge() -> int:
    from friday.config import ensure_runtime_dirs, load_settings, validate_settings
    from friday.telegram_bridge import TelegramBridge, TelegramConfig

    settings = load_settings()
    ensure_runtime_dirs(settings)
    # Surface deny-by-default and credential problems as a clear CLI error before
    # the bridge starts, since validate_settings is otherwise only run by the
    # backend process.
    problems = validate_settings(settings, production=not settings.is_loopback_bind)
    fatal = [item for item in problems if not item.startswith("warning:")]
    if fatal:
        raise ValueError("Invalid Friday configuration: " + "; ".join(fatal))
    token = config_env("FRIDAY_TELEGRAM_BOT_TOKEN", "").strip()
    config = TelegramConfig(
        bot_token=token,
        backend_url=_telegram_backend_url(settings),
        # Native TLS can trust the exact public certificate automatically.  A
        # separately issued CA overrides it; neither path ever exposes the key.
        backend_ca_file=settings.backend_ca_file
        or (settings.ssl_certfile if settings.api_tls_enabled else ""),
        bridge_secret=settings.telegram_bridge_secret,
        allowed_chat_ids=settings.telegram_effective_allowed_chat_ids,
        inbox_db_path=str(settings.state_dir / "telegram-inbox.sqlite3"),
        max_document_bytes=settings.max_upload_bytes,
        # Одно число на обе стороны. Прежняя формула `llm_timeout_sec + 30` жила
        # своей жизнью и на умолчаниях давала 270 с против 720 с, которые
        # разрешены ходу агента: мост бросал запрос, ядро продолжало считать, и
        # доведённая до конца работа выбрасывалась.
        backend_timeout_sec=settings.bridge_backend_timeout_sec,
        telegram_proxy=settings.telegram_proxy,
        open_registration=settings.telegram_open_registration,
        # Outbound delivery polls faster than the reminder scan so a queued
        # message reaches the user promptly rather than on the next scan.
    )
    bridge = TelegramBridge(config)
    try:
        asyncio.run(bridge.run())
    except KeyboardInterrupt:
        print("\nTelegram bridge остановлен.")
    return 0


# Commands not listed here are fail-closed: ``main`` takes both the account-
# deletion contour and backend process leases before their handler runs.  This
# is intentionally the inverse of a list of known mutators; a future maintenance
# command cannot accidentally become a second SQLite writer merely because
# somebody forgot to add it to an inventory.
_CLI_COMMANDS_WITHOUT_ACCOUNT_DATA = frozenset(
    {
        "init",
        "backup-keygen",
        "decrypt-backup",
        "model-check",
        "install-services",
    }
)
_CLI_SERVICE_ROLE_COMMANDS = frozenset(
    {
        "server",
        "telegram-bridge",
        "up",
        "tui",
    }
)
_CLI_COMMANDS_SAFE_WITH_ACTIVE_BACKEND = frozenset(
    {
        "status",
        "doctor",
        "backup",
        "verify-backup",
        "export-user",
        "events",
        "search-source",
    }
)
_CLI_COMMANDS_WITH_SELF_MANAGED_BACKEND_LEASE = frozenset(
    {
        "restore-backup",
        "purge",
    }
)


def _run_cli_handler(args: argparse.Namespace) -> int:
    """Run a CLI command, excluding every default/main-database mutator."""

    command = str(getattr(args, "command", "") or "")
    if command in _CLI_COMMANDS_WITHOUT_ACCOUNT_DATA or command in _CLI_SERVICE_ROLE_COMMANDS:
        return int(args.handler(args) or 0)

    from friday.config import ensure_runtime_dirs, load_settings
    from friday.diagnostics.runtime_lease import ProcessLease

    settings = load_settings()
    ensure_runtime_dirs(settings)
    # Reads, exports and online backups may materialise a pre-deletion snapshot.
    # They can coexist with the ordinary backend, but never with account deletion.
    with ProcessLease(
        settings.state_dir / "account-deletion.lock",
        protocol="friday.account-deletion.v1",
    ):
        if (
            command in _CLI_COMMANDS_SAFE_WITH_ACTIVE_BACKEND
            or command in _CLI_COMMANDS_WITH_SELF_MANAGED_BACKEND_LEASE
        ):
            return int(args.handler(args) or 0)
        with ProcessLease(settings.state_dir / "backend.lock", protocol="friday.backend.v1"):
            return int(args.handler(args) or 0)


