def _decrypt_backup(args: argparse.Namespace) -> int:
    from friday.backup_mirror import decrypt_file
    from friday.config import load_settings

    settings = load_settings()
    key_file = Path(args.key).expanduser() if args.key else settings.backup_encryption_key_file
    if key_file is None:
        print("Укажите --key или задайте FRIDAY_BACKUP_ENCRYPTION_KEY_FILE", file=sys.stderr)
        return 2
    source = Path(args.filename).expanduser()
    destination = (
        Path(args.out).expanduser() if args.out else source.with_name(source.name.removesuffix(".enc"))
    )
    if destination.exists():
        print(f"Не перезаписываю существующий файл: {destination}", file=sys.stderr)
        return 2
    decrypt_file(source, destination, key_file)
    print(f"Расшифровано: {destination}")
    print("Дальше: `jericho verify-backup` рядом с манифестом или `jericho restore-backup`.")
    return 0


