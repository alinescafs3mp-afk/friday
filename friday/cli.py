def _search_source(args: argparse.Namespace) -> int:
    """Search the SOURCE text of ingested material, respecting the Inbox verdict."""
    from friday.config import ensure_runtime_dirs, load_settings
    from friday.permissions import LEGACY_OWNER_USER_ID
    from friday.storage import init_storage

    settings = load_settings()
    ensure_runtime_dirs(settings)
    storage = init_storage(settings)

    try:
        user_id = args.user or LEGACY_OWNER_USER_ID
        items = storage.search_raw_objects(user_id, args.query, limit=args.limit)
        if args.json:
            _json_print({"query": args.query, "items": items, "count": len(items)})
            return 0
        if not items:
            print("Ничего не найдено в доступном исходном тексте.")
            # A source search finding nothing is not proof the phrase was never
            # ingested — only that it is not in material the reviewer kept.
            print("Отклонённый в Inbox материал сюда не входит: это вердикт, а не фильтр.")
            return 0
        for item in items:
            marker = "знание" if item.get("knowledge_object_id") else item.get("inbox_status") or "—"
            print(f"[{marker}] {item.get('source')}: {item.get('source_ref') or item.get('id')}")
            excerpt = str(item.get("excerpt") or "").replace("\n", " ")
            if excerpt:
                print(f"    …{excerpt}…")
        print(f"\nНайдено: {len(items)}")
        return 0
    finally:
        storage.close()


def _events(args: argparse.Namespace) -> int:
    """What happened while nobody was watching."""
    from friday.config import load_settings
    from friday.storage import init_storage

    settings = load_settings()
    storage = init_storage(settings)
    try:
        events = storage.list_events(event_type=args.type, limit=args.limit)
        total = storage.count_events()
    finally:
        storage.close()

    if args.json:
        _json_print(events)
        return 0
    if not events:
        print("Событий пока нет." if not args.type else f"Событий типа {args.type} нет.")
        return 0
    print(f"Последние {len(events)} из {total} записей:\n")
    for event in events:
        stamp = str(event.get("created_at") or "")[:19].replace("T", " ")
        payload = event.get("payload") or {}
        detail = ", ".join(f"{key}={value}" for key, value in payload.items() if value not in (None, ""))
        print(f"  {stamp}  {str(event.get('event_type')):20} {detail}")
    return 0


def _eval_bootstrap(args: argparse.Namespace) -> int:
    """Draft gold cases from existing knowledge; save only what the owner keeps."""
    from friday.agent_runtime.llm import LLMRouter
    from friday.config import ensure_runtime_dirs, load_settings
    from friday.eval_bootstrap import propose_cases, save_accepted
    from friday.storage import init_storage

    settings = load_settings()
    if not settings.llm_enabled:
        print("Нужна работающая модель: FRIDAY_LLM_ENABLED=1.", file=sys.stderr)
        return 2
    ensure_runtime_dirs(settings)
    storage = init_storage(settings)
    try:
        user_id = _resolve_import_user(storage, args.user)
        proposals = asyncio.run(propose_cases(storage, LLMRouter(settings), user_id, limit=args.limit))
        if not proposals:
            print("Не из чего строить: в базе нет знаний.")
            return 0
        accepted = [item for item in proposals if item.accepted]
        for item in proposals:
            if item.accepted:
                print(f"  + {item.query}\n      → {item.title[:70]}")
            else:
                shared = f" ({', '.join(item.shared_tokens)})" if item.shared_tokens else ""
                print(f"  − {item.query or '—'}\n      отклонён: {item.reason}{shared}")
        print(f"\nГодных {len(accepted)} из {len(proposals)}.")
        if not args.save:
            print("Ничего не сохранено. Повторите с --save, если вопросы разумны.")
            return 0
        saved = save_accepted(storage, user_id, accepted)
        print(f"Сохранено кейсов: {saved}. Проверить качество поиска: jericho doctor / раздел «Качество».")
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        return 2
    finally:
        storage.close()
    return 0


def _model_check(args: argparse.Namespace) -> int:
    """Probe the configured endpoint by generating, not by connecting."""
    from friday.config import load_settings
    from friday.model_check import check_model

    settings = load_settings()
    if not settings.llm_enabled:
        print("FRIDAY_LLM_ENABLED=0 — проверяю эндпоинт всё равно, но Friday его не использует.\n")
    report = check_model(settings, timeout=args.timeout)
    if args.json:
        _json_print(report.to_dict())
        return 0 if report.ok else 1

    print(f"Эндпоинт: {report.base_url}\nМодель:   {report.model}\n")
    for probe in report.probes:
        mark = "✓" if probe.ok else "✗"
        timing = f"{probe.seconds:5.2f}s" if probe.seconds else "     "
        tokens = f" {probe.tokens} ток." if probe.tokens is not None else ""
        print(f"  {mark} {probe.name:22} {timing}{tokens}  {probe.detail}")
    print()
    print("Готово к работе." if report.ok else "Есть проблемы — см. отметки ✗ выше.")
    return 0 if report.ok else 1


