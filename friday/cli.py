def _resolve_import_user(storage: Any, requested: str | None) -> str:
    """Pick the tenant to import into, refusing to guess when guessing could misfile.

    A single-account instance is the normal case and asking for --user every time is
    friction for nothing. With several accounts there is no defensible default: the
    files would land in someone's knowledge base, and the wrong one is not recoverable
    by a flag.
    """
    if requested:
        return requested
    users = storage.list_users(limit=5)
    if len(users) == 1:
        return str(users[0]["id"])
    if not users:
        raise ValueError("No accounts exist yet; pass --user to create one for the import")
    raise ValueError(f"{len(users)} accounts exist; pass --user to say which one these files belong to")


def _import(args: argparse.Namespace) -> int:
    """Walk a directory and put every file through the review gate."""
    from friday.bulk_import import Outcome, plan_import, run_import, summarise
    from friday.config import ensure_runtime_dirs, load_settings
    from friday.ingestion import IngestionPipeline
    from friday.knowledge_graph import KnowledgeGraph
    from friday.storage import init_storage

    root = Path(args.path).expanduser()
    if not root.exists():
        print(f"Путь не найден: {root}", file=sys.stderr)
        return 2

    settings = load_settings()
    ensure_runtime_dirs(settings)
    plan = plan_import(
        root,
        max_bytes=settings.max_upload_bytes,
        suffixes=args.suffix,
        include_hidden=args.include_hidden,
        follow_symlinks=args.follow_symlinks,
        # План НЕ ограничивается числом партии: ограничение по плану даёт те же
        # первые N файлов на каждом запуске. Партию отмеряет `run_import` по
        # загруженным. Потолок плана оставлен щедрым, чтобы обход не был бесконечным
        # на дереве, где почти всё уже загружено.
        limit=(args.limit * 20 if args.limit else None),
    )

    megabytes = plan.total_bytes / (1024 * 1024)
    print(f"Найдено файлов: {len(plan.candidates)} ({megabytes:.1f} МиБ), пропущено: {len(plan.skipped)}")
    if plan.candidates:
        shown = list(plan.by_suffix().items())[:8]
        print("  По типам: " + ", ".join(f"{suffix} {count}" for suffix, count in shown))
    if plan.skipped:
        print("  Пропущено: " + ", ".join(f"{why} {count}" for why, count in plan.skip_reasons().items()))
    if args.dry_run:
        print("\n--dry-run: ничего не записано.")
        return 0
    if not plan.candidates:
        return 0

    storage = init_storage(settings)
    try:
        try:
            user_id = _resolve_import_user(storage, args.user)
        except ValueError as exc:
            print(str(exc), file=sys.stderr)
            return 2
        uploaded_by = str(args.uploaded_by or "").strip() or None
        if uploaded_by is not None and uploaded_by != user_id and storage.get_user(uploaded_by) is None:
            print(
                f"Аккаунт автора загрузки не найден: {uploaded_by}. "
                "Создайте его или не передавайте --uploaded-by, чтобы честно записать автора неизвестным.",
                file=sys.stderr,
            )
            return 2
        pipeline = IngestionPipeline(settings, storage, KnowledgeGraph(storage), None)
        print(f"Импорт в аккаунт {user_id}. Всё уходит в Inbox на ваше подтверждение.\n")
        if uploaded_by is None:
            print(
                "Автор загрузки неизвестен: uploaded_by будет записан как null. "
                "Если человек известен, повторите с --uploaded-by ACCOUNT_ID.\n"
            )

        def progress(index: int, total: int, outcome: Outcome) -> None:
            if outcome.status == "failed":
                print(f"  [{index}/{total}] ОШИБКА {outcome.path}: {outcome.detail}", file=sys.stderr)
            elif not args.quiet:
                mark = "=" if outcome.status == "duplicate" else "+"
                print(f"  [{index}/{total}] {mark} {outcome.path.name}")

        try:
            outcomes = asyncio.run(
                run_import(
                    pipeline,
                    user_id,
                    plan,
                    uploaded_by=uploaded_by,
                    on_progress=progress,
                    stop_after=args.limit,
                )
            )
        except KeyboardInterrupt:
            # Content-hash idempotency means a re-run resumes; say so rather than
            # leaving the user guessing whether they have to start over.
            print("\nПрервано. Повторите ту же команду — уже загруженные файлы будут пропущены.")
            return 130
    finally:
        storage.close()

    counts = summarise(outcomes)
    print(
        f"\nГотово: загружено {counts['ingested']}, "
        f"без содержимого {counts['empty']}, "
        f"уже было {counts['duplicate']}, ошибок {counts['failed']}."
    )
    if counts["empty"]:
        # Отдельной строкой, потому что следующий шаг у них другой: спрашивать по
        # ним нечего, и человек должен знать это до того, как спросит.
        print(
            f"  Из них {counts['empty']} файлов сохранены, но текста из них не вышло — "
            "сканы без текстового слоя, пустые заготовки, битые выгрузки."
        )
    if counts["ingested"]:
        print("Разобрать: /inbox в Telegram или раздел Inbox в админке.")
    return 1 if counts["failed"] else 0


def _reindex_embeddings(args: argparse.Namespace) -> int:
    """Заставить индексатор пересчитать вектора, не оставляя поиск без них.

    Понадобилось потому, что вектор, посчитанный по неверному тексту, в базе
    неотличим от honest: хэш пишется от полного текста. Когда такое обнаружено —
    заменой лечения на отказ по длине, сменой модели, правкой потолков — нужен
    способ сказать «пересчитай всё», и он не должен требовать ни остановки
    сервиса, ни ручного удаления строк.

    Работает пометкой, а не удалением: старый вектор продолжает отвечать на поиск,
    пока индексатор не заменит его. Поэтому команда безопасна на живой системе —
    худшее, что она делает, это работа для видеокарты.
    """

    if not args.yes:
        print(
            "Команда пометит вектора устаревшими, и фоновый индексатор пересчитает их заново. "
            "Поиск продолжит работать на прежних векторах до замены. Повторите с --yes.",
            file=sys.stderr,
        )
        return 2

    from friday.config import ensure_runtime_dirs, load_settings
    from friday.storage import init_storage

    settings = load_settings()
    ensure_runtime_dirs(settings)
    storage = init_storage(settings)
    try:
        marked = storage.mark_embeddings_stale(user_id=args.user)
        storage.record_event(
            "embeddings.reindex_requested",
            {"marked": marked, "user_id": args.user or "*"},
        )
    finally:
        storage.close()
    scope = f"арендатора {args.user}" if args.user else "всех арендаторов"
    print(f"Помечено устаревшими векторов {scope}: {marked}.")
    print("Пересчёт идёт фоновым индексатором; следите за `jericho status` или журналом.")
    return 0


def _backfill_document_dates(args: argparse.Namespace) -> int:
    """Достать собственную дату документа у уже загруженных файлов.

    Дату из провенанса файла (docProps/core.xml, /CreationDate) начали снимать
    при приёме, а корпус загружен раньше: у владельца дата создания у 1531
    объекта из 1537 — это день импорта, то есть хронологии архива не было вовсе.
    Замер на его же файлах: 84% дают настоящую дату, разброс 2006-2026.

    Безопасно на живой системе: читает файлы, пишет ОДНО поле метаданных и не
    создаёт версий — это дозапись утраченного провенанса, а не правка знания.
    Идемпотентно: объект с датой второй раз не берётся, поэтому прерванный
    прогон продолжается повторным запуском.
    """
    from friday.config import ensure_runtime_dirs, load_settings
    from friday.documents import _office_document_date, _pdf_document_date_from_bytes
    from friday.storage import init_storage

    settings = load_settings()
    ensure_runtime_dirs(settings)
    storage = init_storage(settings)
    scanned = dated = missing = 0
    # Курсор, а не множество просмотренных. Объект, у которого даты в файле НЕТ,
    # остаётся «без даты» навсегда, поэтому выборка «первые N без даты» отдаёт его
    # снова и снова: прежний цикл отфильтровывал их по `seen`, получал пустую
    # пачку и ВЫХОДИЛ — считая концом корпуса то, что было концом первой страницы.
    # Повторный запуск начинал с той же головы и не двигался дальше никогда.
    # Замер на копии боевой базы: 184 объекта без даты при batch=200 — сегодня
    # укладывается, но ровно поэтому дефект и не проявился ни разу; корпус растёт.
    cursor = 0
    try:
        while True:
            batch = storage.knowledge_missing_document_date(
                user_id=args.user, limit=args.batch, after_rowid=cursor
            )
            if not batch:
                break
            for row in batch:
                cursor = max(cursor, int(row["position"]))
                scanned += 1
                raw_path = str(row.get("stored_path") or "")
                path = pathlib.Path(raw_path)
                if not path.is_absolute():
                    path = settings.files_dir / path
                try:
                    content = path.read_bytes()
                except OSError:
                    missing += 1
                    continue
                if content[:2] == b"PK":
                    found = _office_document_date(content)
                elif content[:5] == b"%PDF-":
                    found = _pdf_document_date_from_bytes(content)
                else:
                    found = None
                if found and storage.set_document_date(str(row["id"]), str(row["user_id"]), found):
                    dated += 1
            if args.limit and scanned >= args.limit:
                break
        storage.record_event(
            "documents.dates_backfilled",
            {"scanned": scanned, "dated": dated, "files_missing": missing},
        )
    finally:
        storage.close()
    print(f"Просмотрено объектов: {scanned}; проставлено дат: {dated}; файлов не найдено: {missing}.")
    if scanned and not dated:
        print("Ни одной даты: у этих форматов её нет в файле — это не ошибка, а отсутствие данных.")
    return 0


def warn_if_service_holds_the_database(storage: Any, *, action: str) -> bool:
    """Сказать вслух, что heartbeat ещё считает службу живой.

    Два процесса, одновременно пишущие в одну базу SQLite, — это не теория.
    Живой экземпляр упал 2026-08-05 в 00:22:29: сигнал 7 (SIGBUS), стек целиком
    внутри libsqlite3, адрес обращения `0x79f73fdcd000` — внутри отображения
    `79f73fdc9000-79f73fdd1000 rw-s … jericho.sqlite3-shm`. То есть файл общей
    памяти WAL стал короче собственного отображения. В ту же минуту по той же
    базе шёл проход `retag-documents --apply` ВТОРЫМ процессом.

    База уцелела (`integrity_check` = ok), служба поднялась сама через 19 секунд,
    но запросы человека в эти секунды оборвались, а мост потерял бэкенд с
    `httpx.ReadError`.

    Прагмой это не лечится: `PRAGMA persist_wal` в SQLite нет вовсе, а неизвестные
    прагмы молча игнорируются — проверено исполнением, файлы `-wal`/`-shm` после
    закрытия удаляются как ни в чём не бывало.

    Командная граница теперь берёт ``backend.lock`` ДО вызова изменяющего
    обработчика и не допускает второго писателя вовсе. Эта проверка остаётся
    поясняющей диагностикой для старого heartbeat и прямых внутренних вызовов;
    она больше не является единственным предохранителем.
    """

    age = storage.live_service_heartbeat_age()
    if age is None:
        return False
    print(
        f"⚠️  Базу держит живая служба (отметилась {age:.0f} с назад), а этот проход будет {action}.",
        file=sys.stderr,
    )
    print(
        "    Два процесса, пишущие в одну базу SQLite, уже роняли живой экземпляр "
        "по SIGBUS 2026-08-05 в 00:22 (данные уцелели, простой 19 с).",
        file=sys.stderr,
    )
    print(
        "    Надёжнее: `systemctl --user stop friday-backend`, проход, потом start.",
        file=sys.stderr,
    )
    return True


def _backfill_entities(args: argparse.Namespace) -> int:
    """Провести ОБЪЯВЛЯЮЩЕЕ правило извлечения по УЖЕ загруженному архиву.

    Правило, добавленное после загрузки корпуса, на лежащие в базе документы не
    действует вовсе — извлечение работает только при приёме. Такой проход и есть
    способ это исправить.

    Метод называется явно и только один за прогон: остальные отработали при приёме,
    и повторный прогон по ним означал бы новое решение за человека там, где его уже
    спрашивали. Разрешены только ОБЪЯВЛЯЮЩИЕ методы (`DECLARED_ENTITY_METHODS`) —
    те, у которых есть право само создавать узел; догадка по форме слова таким
    правом не обладает и через этот проход пройти не должна.

    Чем уже пользовались:

      explicit_person_patronymic — ФИО с отчеством. Замер на 900 документах: 6094
        упоминания, 3069 различных ФИО; на всех 1532 объектах — 20 644 упоминания и
        4349 узлов, 71% имён встречается больше чем в одном документе, перестановочных
        двойников 4 из 4349. Точность 100% на 80 именах при судье, проверенном 6 из 6.

      explicit_military_unit — «в/ч N» и «войсковая часть N». Замер на живом архиве:
        240 документов, 151 различная часть, 67 из них более чем в одном документе,
        1079 пар «человек и часть» в пределах абзаца. До правила извлекалось НОЛЬ.

    По умолчанию — ПОКАЗ: считает и не пишет. Запись включает `--apply`.
    """
    from friday.config import ensure_runtime_dirs, load_settings
    from friday.ingestion import _extract_entities
    from friday.ingestion._base import DECLARED_ENTITY_METHODS
    from friday.knowledge_graph import KnowledgeGraph
    from friday.storage import init_storage
    from friday.storage.models import EntityType

    method = str(args.method)
    if method not in DECLARED_ENTITY_METHODS:
        print(
            f"Метод {method!r} не объявляющий. Проход умеет только те, что вправе сами "
            f"создавать узел:\n  " + "\n  ".join(sorted(DECLARED_ENTITY_METHODS)),
            file=sys.stderr,
        )
        return 2

    settings = load_settings()
    ensure_runtime_dirs(settings)
    storage = init_storage(settings)
    graph = KnowledgeGraph(storage)
    apply_changes = bool(getattr(args, "apply", False))
    scanned = mentions = created = linked = skipped_decided = 0
    names: set[str] = set()
    cursor = 0
    try:
        while True:
            batch = storage.knowledge_bodies_after(after_rowid=cursor, user_id=args.user, limit=args.batch)
            if not batch:
                break
            for row in batch:
                cursor = int(row["rowid"])
                scanned += 1
                ko_id, owner = str(row["id"]), str(row["user_id"])
                candidates = [
                    item
                    for item in _extract_entities(str(row["content"] or ""))
                    if str(item.get("method") or "") == method
                ]
                if not candidates:
                    continue
                decided = storage.decided_entity_links(owner, ko_id) if apply_changes else set()
                for candidate in candidates:
                    mentions += 1
                    name = str(candidate.get("name") or "").strip()
                    if not name:
                        continue
                    names.add(name.casefold())
                    if not apply_changes:
                        continue
                    entity = graph.find_entity(owner, name)
                    if not entity:
                        try:
                            entity = graph.create_entity(
                                owner,
                                name,
                                EntityType(str(candidate.get("entity_type") or EntityType.OTHER.value)),
                                metadata={
                                    "created_by": "backfill_entities",
                                    "extraction_method": method,
                                    "initial_confidence": float(candidate.get("confidence", 0.9)),
                                },
                            )
                            created += 1
                        except (ValueError, KeyError):
                            continue
                    if str(entity["id"]) in decided:
                        # Человек уже высказался про эту пару. Проход не спорит с ним.
                        skipped_decided += 1
                        continue
                    graph.link_knowledge_to_entity(
                        ko_id,
                        str(entity["id"]),
                        owner,
                        confidence=float(candidate.get("confidence", 0.9)),
                        evidence={
                            "method": method,
                            "matched_as": candidate.get("matched_as", name),
                            "backfill": True,
                        },
                        status="accepted",
                    )
                    linked += 1
            if args.limit and scanned >= args.limit:
                break
        if apply_changes:
            storage.record_event(
                "graph.entities_backfilled",
                {
                    "method": method,
                    "scanned": scanned,
                    "mentions": mentions,
                    "distinct_names": len(names),
                    "entities_created": created,
                    "links": linked,
                    "skipped_decided": skipped_decided,
                },
            )
    finally:
        storage.close()
    # «Упоминаний» здесь — это пары (документ, имя), а не вхождения в текст:
    # `_extract_entities` схлопывает одинаковые имена внутри документа. Отдельная проба
    # по сырому тексту даёт больше (1522 против 464 у частей), и это не расхождение,
    # а разные величины — путать их значит спорить с собственным замером.
    print(
        f"Метод: {method}. Просмотрено объектов: {scanned}; "
        f"пар документ-имя: {mentions}; различных имён: {len(names)}."
    )
    if apply_changes:
        print(
            f"Создано сущностей: {created}; связей знание-человек: {linked}; "
            f"обойдено решённых человеком: {skipped_decided}."
        )
    else:
        print("Это ПОКАЗ, в базу ничего не записано. Чтобы применить, повторите с --apply.")
    return 0


def _prune_entities(args: argparse.Namespace) -> int:
    """Убрать узлы, которых ТЕКУЩИЕ правила больше не порождают.

    Починка правила извлечения действует только вперёд. Узел, заведённый прежней
    редакцией, остаётся в графе навсегда и — что хуже — продолжает собирать
    привязки: сопоставление упоминаний работает от СУЩЕСТВУЮЩИХ имён, и одна
    ошибка разрастается. Узел «Викторович» (отчество, принятое за имя сервера)
    завёлся по одному документу и набрал 314 привязок в документах про разных
    людей — концентратор из ничего.

    Проход не судит имя и не знает никаких списков мусора. Он спрашивает ровно
    одно: породили бы сегодняшние правила это имя хоть на одном документе архива?
    Если нет — узла быть не должно.

    Четыре запрета, и каждый оплачен ошибкой — три из них МОЕЙ, найденной первым же
    прогоном этого прохода по живому графу:

    * Рождён ли узел правилом, спрашивается у САМОГО МЕТОДА, а не у имени прохода.
      Первая редакция держала список «ingestion, backfill_entities» — и не знала, что
      4349 узлов-людей заведены проходом под прежним именем `backfill_person_entities`.
      Вся людская половина графа молча считалась чужой, а проход при этом отчитывался
      как отработавший. Имена проходов меняются, набор методов извлечения — это
      объявленный инвентарь (`DECLARED` + `EVIDENCE_ONLY`), и спрашивать надо его.
    * Сверка идёт с ТЕМ ЖЕ правилом, которое узел завело. Первая редакция сравнивала
      имя со всеми правилами разом, и «Курган Курганская» уцелел: слабое правило «два
      слова с заглавной» выдаёт ту же строку кандидатом в люди. Мусорное место
      пряталось за догадкой о человеке.
    * Узел остаётся и в том случае, если его имя сегодня объявляет ЛЮБОЕ сильное
      правило: метод узла мог смениться на более уверенный, и это не повод сносить.
    * Узел остаётся, если сегодняшние правила объявляют ТЕ ЖЕ СЛОВА в другом порядке.
      «Руслан Рашитович Хасанов» и «ХАСАНОВ Руслан Рашитович» — один человек, и
      разный порядок слов означает вопрос о СЛИЯНИИ, а не о мусоре; у слияния свой
      разбор и своя очередь. Один такой на 188 отобранных — и он бы исчез вместе
      со всеми своими привязками.
    * Ни одной привязки, которую человек посмотрел или отклонил: решение человека
      в этой системе — вершина, и разовый проход с ним не спорит.

    По умолчанию ПОКАЗ. Запись включает `--apply`, и она мягкая: `deleted_at`
    ставится новой версией, обратный ход — `undelete_entity`.
    """
    from friday.config import ensure_runtime_dirs, load_settings
    from friday.ingestion import _extract_entities
    from friday.ingestion._base import DECLARED_ENTITY_METHODS, EVIDENCE_ONLY_ENTITY_METHODS
    from friday.storage import init_storage
    from friday.storage._base import normalize_entity_name

    settings = load_settings()
    ensure_runtime_dirs(settings)
    storage = init_storage(settings)
    apply_changes = bool(getattr(args, "apply", False))
    born_of_a_rule = DECLARED_ENTITY_METHODS | EVIDENCE_ONLY_ENTITY_METHODS

    scanned = 0
    produced: set[tuple[str, str, str]] = set()
    declared: set[tuple[str, str]] = set()
    declared_bags: set[tuple[str, frozenset[str]]] = set()
    owners: set[str] = set()
    doomed: list[dict[str, Any]] = []
    kept_reviewed = kept_foreign = kept_permuted = 0
    try:
        cursor = 0
        while True:
            batch = storage.knowledge_bodies_after(after_rowid=cursor, user_id=args.user, limit=args.batch)
            if not batch:
                break
            for row in batch:
                cursor = int(row["rowid"])
                scanned += 1
                owner = str(row["user_id"])
                owners.add(owner)
                text = f"{row['title'] or ''}\n{row['content'] or ''}"
                for item in _extract_entities(text):
                    name = normalize_entity_name(str(item.get("name") or ""))
                    method = str(item.get("method") or "")
                    produced.add((owner, method, name))
                    if method in DECLARED_ENTITY_METHODS:
                        declared.add((owner, name))
                        declared_bags.add((owner, frozenset(name.split())))
            if args.limit and scanned >= args.limit:
                break

        if args.limit and scanned >= args.limit:
            # Половина корпуса — половина порождённых имён, и всё остальное
            # объявляется мусором. Такой прогон годится только посмотреть.
            print(
                f"--limit {args.limit} оборвал просмотр на {scanned} объектах: "
                f"неполный корпус даёт неполный список порождённых имён, и удалять по нему нельзя.",
                file=sys.stderr,
            )
            return 2

        for owner in sorted(owners if not args.user else {str(args.user)}):
            for entity in storage.iter_entities(owner):
                metadata = entity.get("metadata_json")
                meta = json.loads(metadata) if isinstance(metadata, str) and metadata else (metadata or {})
                method = str(meta.get("extraction_method") or "")
                if method not in born_of_a_rule:
                    kept_foreign += 1
                    continue
                normalized = str(entity.get("normalized_name") or normalize_entity_name(str(entity["name"])))
                if (owner, method, normalized) in produced or (owner, normalized) in declared:
                    continue
                if (owner, frozenset(normalized.split())) in declared_bags:
                    kept_permuted += 1
                    continue
                if storage.entity_links_touched_by_a_person(str(entity["id"]), owner):
                    kept_reviewed += 1
                    continue
                doomed.append(entity)

        for entity in doomed:
            print(
                f"  [{entity['entity_type']}] {entity['name']}  "
                f"(правило: {(json.loads(entity['metadata_json']) if isinstance(entity.get('metadata_json'), str) and entity.get('metadata_json') else {}).get('extraction_method', '?')})"
            )
            if apply_changes:
                storage.soft_delete_entity(str(entity["id"]), str(entity["user_id"]))
        if apply_changes and doomed:
            storage.record_event(
                "graph.entities_pruned",
                {
                    "scanned": scanned,
                    "removed": len(doomed),
                    "names": [str(e["name"]) for e in doomed][:200],
                    # Names are personal material without an intrinsic tenant id.
                    # Recording the closed owner set lets account deletion find
                    # the row and makes record_event's tombstone barrier reject a
                    # stale CLI pass which resumes after that owner was erased.
                    "user_ids": sorted({str(entity["user_id"]) for entity in doomed}),
                },
            )
    finally:
        storage.close()

    print(
        f"Просмотрено объектов: {scanned}; пар правило-имя у сегодняшних правил: {len(produced)}, "
        f"из них объявленных: {len(declared)}. Узлов под снос: {len(doomed)}; "
        f"оставлено не рождённых правилом: {kept_foreign}; оставлено решённых человеком: {kept_reviewed}; "
        f"оставлено перестановок живого имени: {kept_permuted}."
    )
    if not apply_changes:
        print("Это ПОКАЗ, в базу ничего не записано. Чтобы применить, повторите с --apply.")
    return 0


def _backfill_relations(args: argparse.Namespace) -> int:
    """Провести извлечение СВЯЗЕЙ по уже загруженному архиву.

    Та же беда, что у сущностей: правило действует только при приёме документа, а
    корпус загружен раньше. В графе владельца было 4610 сущностей и НОЛЬ связей —
    не потому, что механизм сломан, а потому, что его никто не звал.

    Замерено на копии базы 2026-08-03 (проход по всем 1533 документам):

        без родственных слов                      0 кандидатов
        со словами, без проверок             509 кандидатов, мусор: «Изобильный
                                             -> Москва | Брат» — два города
        + обе стороны люди                   243 кандидата, половина сцепляет
                                             людей из РАЗНЫХ анкет заголовком поля
        + слово вплотную к имени              98 кандидатов, из них 4 от «внук» —
                                             все из одного списка позывных
        + «внук» убран из словаря             94 кандидата на 56 документах,
                                             около 85% верных на глаз

    Результат — ОЧЕРЕДЬ НА ПОДТВЕРЖДЕНИЕ, а не готовые связи: каждый кандидат
    ждёт решения человека. Поэтому по умолчанию — показ, запись включает `--apply`.
    """
    from friday.config import ensure_runtime_dirs, load_settings
    from friday.knowledge_graph import KnowledgeGraph
    from friday.storage import init_storage

    settings = load_settings()
    ensure_runtime_dirs(settings)
    storage = init_storage(settings)
    graph = KnowledgeGraph(storage)
    apply_changes = bool(getattr(args, "apply", False))
    scanned = found = touched = 0
    #: Одна и та же пара, названная в трёх документах, — три СРАБАТЫВАНИЯ и одна
    #: связь: хранилище схлопывает их по (источник, цель, тип). Считать надо оба
    #: числа. Замерено: 94 срабатывания дали 64 различных пары, и печатать первое
    #: как «кандидатов в связи» значило бы выдать работу прохода за содержимое
    #: очереди — тот же класс, что «длина страницы — не факт о корпусе».
    pairs: set[str] = set()
    cursor = 0
    try:
        while True:
            batch = storage.knowledge_bodies_after(after_rowid=cursor, user_id=args.user, limit=args.batch)
            if not batch:
                break
            for row in batch:
                cursor = int(row["rowid"])
                scanned += 1
                if not apply_changes:
                    # Показ считает документы, а не кандидатов: сам разбор ПИШЕТ
                    # в базу, и «сухой» его вариант был бы вторым кодом, который
                    # мерит уже не то, что применится.
                    continue
                try:
                    made = graph.suggest_relations_for_knowledge(str(row["user_id"]), str(row["id"]))
                except Exception as error:  # noqa: BLE001 — один документ не должен рвать проход
                    print(f"  {row['id']}: {type(error).__name__}: {error}", file=sys.stderr)
                    continue
                if made:
                    found += len(made)
                    pairs.update(str(item.get("id") or "") for item in made if item.get("id"))
                    touched += 1
            if args.limit and scanned >= args.limit:
                break
        if apply_changes:
            storage.record_event(
                "graph.relations_backfilled",
                {
                    "scanned": scanned,
                    "matches": found,
                    "candidates": len(pairs),
                    "documents": touched,
                },
            )
    finally:
        storage.close()
    print(f"Просмотрено объектов: {scanned}.")
    if apply_changes:
        print(
            f"Срабатываний: {found}; различных пар в очереди: {len(pairs)}; документов со связями: {touched}."
        )
        print("Это КАНДИДАТЫ — каждый ждёт подтверждения человеком в панели.")
    else:
        print("Это ПОКАЗ, в базу ничего не записано. Чтобы применить, повторите с --apply.")
    return 0


def _extract_structure_relations(args: argparse.Namespace) -> int:
    """Связи, объявленные ФОРМОЙ документа, — арбитром по всему архиву.

    Второй проход рядом с `backfill-relations`, а не замена ему. Фразовый ищет
    объявляющее слово между двумя именами и связывает эти два имени; форма
    служебного документа объявляет отношения СУБЪЕКТА — того, чья это анкета,
    чей это пункт списка, кто подписал рапорт. Замерено на архиве владельца: в
    рапорте из восьми фразовых пар верны три, и те случайно.

    Требуется модель: форм в архиве больше десятка (анкет 167, рапортов 5,
    прочего 1360 — ведомости, списки, книги, планы, выписки, листы Excel), и
    каждая новая форма при шаблонном разборе снова даёт ноль.

    Результат — ОЧЕРЕДЬ НА ПОДТВЕРЖДЕНИЕ. По умолчанию показ, запись включает
    `--apply`; показ здесь настоящий — арбитр вызывается с `store=False`.
    """
    import asyncio

    from friday.agent_runtime.llm import LLMRouter
    from friday.config import ensure_runtime_dirs, load_settings
    from friday.knowledge_graph import KnowledgeGraph
    from friday.storage import init_storage

    settings = load_settings()
    ensure_runtime_dirs(settings)
    storage = init_storage(settings)
    graph = KnowledgeGraph(storage)
    llm = LLMRouter(settings)
    if not llm.enabled:
        print("Модель выключена: разбор формы документа без неё невозможен.", file=sys.stderr)
        storage.close()
        return 2
    apply_changes = bool(getattr(args, "apply", False))

    async def run() -> tuple[int, int, int, int, int]:
        scanned = proposed = kept = skipped_windows = model_errors = 0
        cursor = 0
        while True:
            batch = storage.knowledge_bodies_after(after_rowid=cursor, user_id=args.user, limit=args.batch)
            if not batch:
                break
            for row in batch:
                cursor = int(row["rowid"])
                scanned += 1
                try:
                    result = await graph.suggest_relations_from_structure(
                        str(row["user_id"]),
                        str(row["id"]),
                        llm=llm,
                        store=apply_changes,
                    )
                except Exception as error:  # noqa: BLE001 — один документ не рвёт проход
                    print(f"  {row['id']}: {type(error).__name__}: {error}", file=sys.stderr)
                    continue
                proposed += int(result.get("proposed") or 0)
                kept += len(result.get("candidates") or [])
                skipped_windows += int(result.get("windows_skipped") or 0)
                model_errors += int(result.get("model_errors") or 0)
            if args.limit and scanned >= args.limit:
                break
        return scanned, proposed, kept, skipped_windows, model_errors

    try:
        scanned, proposed, kept, skipped_windows, model_errors = asyncio.run(run())
        if apply_changes:
            storage.record_event(
                "graph.structure_relations_extracted",
                {"scanned": scanned, "proposed": proposed, "kept": kept},
            )
    finally:
        storage.close()
    print(f"Просмотрено объектов: {scanned}.")
    print(f"Арбитр предложил: {proposed}; прошло проверки: {kept}.")
    if skipped_windows:
        # Названо вслух: молча недочитанный документ выглядит как разобранный.
        print(f"НЕ прочитано окон (документы длиннее потолка): {skipped_windows}.")
    if model_errors:
        # Недоступная модель даёт «просмотрено 1532, предложено 0» — то же, что
        # архив без единой объявленной связи. Поймано на первом проходе: 83
        # неудачных вызова подряд и ни слова о причине, потому что адрес брался
        # из умолчания (файл окружения лежит рядом с базой, а не в текущем
        # каталоге). Проход не считается выполненным, если модель молчала.
        print(
            f"ОШИБОК ВЫЗОВА МОДЕЛИ: {model_errors} — столько окон осталось неразобранными.",
            file=sys.stderr,
        )
        if not kept:
            print(
                "Ни одно окно не разобрано. Проверьте адрес модели: "
                f"{llm.base_url} (файл окружения — FRIDAY_ENV_FILE).",
                file=sys.stderr,
            )
            return 1
    if apply_changes:
        print("Это КАНДИДАТЫ — каждый ждёт подтверждения человеком в панели.")
    else:
        print("Это ПОКАЗ, в базу ничего не записано. Чтобы применить, повторите с --apply.")
    return 0


def _retag_documents(args: argparse.Namespace) -> int:
    """Проставить архиву ВИД документа и снять теги прежней редакции правил.

    Правило чинится вперёд, а узлы прежней редакции остаются: теги `document` и
    `application` код не порождает с 2026-07-29 (последний объект с ними создан
    в тот день), но на живом архиве они сидят на 1524 объектах из 1536 — 99.2%,
    то есть 19.2% всего тегового объёма занято двумя тегами, не сужающими ничего.

    Показ по умолчанию. Замер перед применением — на архиве владельца вид
    объявляют о себе 88.2% документов; остальным вид не приписывается, потому
    что тег «рапорт» на списке личного состава хуже отсутствия тега: по нему
    будут отбирать.
    """

    import asyncio

    from friday.config import ensure_runtime_dirs, load_settings
    from friday.ingestion._boilerplate import learn_boilerplate, store_boilerplate
    from friday.ingestion._document_kind import KIND_TAG_PREFIX, detect_document_kind, kind_tag
    from friday.storage import init_storage

    #: Теги прежней редакции: вид НОСИТЕЛЯ (`document`) и первая часть mime-типа
    #: (`application`), приписывавшиеся каждому файлу без анализа содержимого.
    _STALE_TAGS = frozenset({"document", "application"})

    settings = load_settings()
    ensure_runtime_dirs(settings)
    storage = init_storage(settings)
    apply_changes = bool(getattr(args, "apply", False))
    if apply_changes:
        warn_if_service_holds_the_database(storage, action="переписывать теги")
    use_arbiter = bool(getattr(args, "arbiter", False))
    llm = None
    if use_arbiter:
        from friday.agent_runtime.llm import LLMRouter

        llm = LLMRouter(settings)
        if not llm.enabled:
            print("Модель выключена: арбитр вида недоступен.", file=sys.stderr)
            storage.close()
            return 2
    report_path = getattr(args, "report", None)
    report_file = open_private_text_write(Path(report_path)) if report_path else None

    seen = kinds_set = stale_removed = changed = asked = 0
    by_kind: dict[str, int] = {}
    proposals: dict[str, int] = {}
    learned: dict[str, Any] = {}
    rebuild = bool(getattr(args, "rebuild_tags", False))
    pipeline = None
    if rebuild:
        from friday.ingestion import IngestionPipeline

        pipeline = IngestionPipeline(settings, storage)

    if bool(getattr(args, "learn_boilerplate", False)):
        # Считается ДО разметки и по всему корпусу: слово бланка узнаётся только
        # по тому, что его окружение повторяется в других документах.
        bodies: list[str] = []
        cursor = 0
        while True:
            batch = storage.knowledge_bodies_after(after_rowid=cursor, user_id=args.user, limit=200)
            if not batch:
                break
            for row in batch:
                cursor = int(row["rowid"])
                current = storage.get_knowledge_object(str(row["id"]), str(row["user_id"]))
                if current:
                    bodies.append(str(current.get("content") or ""))
        learned = learn_boilerplate(bodies)
        print(
            f"Слов бланка найдено: {len(learned['words'])} "
            f"(рассмотрено {learned['considered']} слов на {learned['documents']} документах)."
        )
        print("    " + ", ".join(learned["words"][:24]))
        if apply_changes:
            store_boilerplate(storage, learned)
        else:
            print("    ПОКАЗ: список не сохранён.")

    async def run() -> None:
        nonlocal seen, kinds_set, stale_removed, changed, asked
        cursor = 0
        while True:
            batch = storage.knowledge_bodies_after(after_rowid=cursor, user_id=args.user, limit=args.batch)
            if not batch:
                break
            for row in batch:
                cursor = int(row["rowid"])
                seen += 1
                current = storage.get_knowledge_object(str(row["id"]), str(row["user_id"]))
                if not current:
                    continue
                original = list(json.loads(current.get("tags_json") or "[]"))
                tags = list(original)
                content = str(current.get("content") or "")
                title = str(current.get("title") or "")
                if rebuild:
                    # Теги пересобираются ТОЙ ЖЕ дорогой, что и при приёме
                    # (`_enrich`), а не второй копией правил рядом. Иначе проход
                    # и приём разойдутся ровно в тот день, когда правило
                    # поменяют в одном месте из двух.
                    #
                    # Берутся только теги: `reenrich_knowledge` переписал бы ещё
                    # заголовок и сводку, а у файлового архива заголовок — это
                    # имя файла, и менять его проход не просили.
                    assert pipeline is not None
                    enrichment = pipeline._enrich(
                        content,
                        pipeline.assess_text(content),
                        user_id=str(row["user_id"]),
                        title=title,
                        # Только что посчитанный список идёт в обогащение прямо,
                        # а не через базу: иначе показ врёт. Первый прогон это и
                        # показал — «абонентский» и «работает» остались в новых
                        # тегах, потому что показ список не сохраняет, а
                        # `_enrich` читает сохранённый.
                        extra_blocked=frozenset(learned.get("words") or ()),
                    )
                    tags = list(enrichment.tags)
                kind, evidence = detect_document_kind(content, title=title)
                if not kind and llm is not None:
                    from friday.ingestion._document_kind import ask_document_kind

                    asked += 1
                    try:
                        kind, evidence = await ask_document_kind(content, llm=llm)
                    except Exception as error:  # noqa: BLE001 — один документ не рвёт проход
                        print(f"  {row['id']}: {type(error).__name__}: {error}", file=sys.stderr)
                        kind, evidence = "", ""
                    if not kind and evidence.startswith("другое: "):
                        proposals[evidence[8:]] = proposals.get(evidence[8:], 0) + 1
                # Прежний вид снимается только тогда, когда есть чем заменить.
                # Иначе повторный проход БЕЗ `--arbiter` стирал бы виды, которые
                # арбитр проставил в прошлый раз: быстрый путь их не находит по
                # построению — за тем арбитра и звали. Проход, умеющий только
                # разрушать чужую работу, хуже, чем не запущенный.
                kept = [
                    tag
                    for tag in tags
                    if tag not in _STALE_TAGS and (not tag.startswith(KIND_TAG_PREFIX) or not kind)
                ]
                stale_removed += len([tag for tag in original if tag in _STALE_TAGS])
                if kind:
                    kept.append(kind_tag(kind))
                    kinds_set += 1
                    by_kind[kind] = by_kind.get(kind, 0) + 1
                elif any(tag.startswith(KIND_TAG_PREFIX) for tag in original):
                    # Вид уже стоял и остаётся: его поставили прошлым проходом.
                    # Берётся из ИСХОДНЫХ тегов: пересборка его не порождает —
                    # быстрый путь этот вид не нашёл, за тем и звали арбитра.
                    kinds_set += 1
                    kept.append(next(tag for tag in original if tag.startswith(KIND_TAG_PREFIX)))
                    previous = next(tag for tag in original if tag.startswith(KIND_TAG_PREFIX))
                    by_kind[previous[len(KIND_TAG_PREFIX) :]] = (
                        by_kind.get(previous[len(KIND_TAG_PREFIX) :], 0) + 1
                    )
                new_tags = sorted(set(kept))
                if report_file is not None:
                    report_file.write(
                        json.dumps(
                            {
                                "id": row["id"],
                                "title": title[:120],
                                "kind": kind,
                                "evidence": evidence,
                                "removed": sorted(set(original) - set(new_tags)),
                                "added": sorted(set(new_tags) - set(original)),
                            },
                            ensure_ascii=False,
                        )
                        + "\n"
                    )
                if new_tags == sorted(set(original)):
                    continue
                changed += 1
                if apply_changes:
                    storage.update_knowledge_fields(str(row["id"]), str(row["user_id"]), tags_json=new_tags)
            if args.limit and seen >= args.limit:
                break

    try:
        asyncio.run(run())
        if apply_changes:
            storage.record_event(
                "knowledge.retagged",
                {"seen": seen, "kinds": kinds_set, "changed": changed},
            )
    finally:
        if report_file is not None:
            report_file.close()
        storage.close()

    print(f"Просмотрено объектов: {seen}.")
    print(f"Вид объявлен у: {kinds_set} ({kinds_set / max(seen, 1) * 100:.1f}%)")
    for kind, count in sorted(by_kind.items(), key=lambda item: -item[1]):
        print(f"    {kind:26s} {count:5d}")
    print(f"Снято тегов прежней редакции: {stale_removed}.")
    if asked:
        print(f"Спрошено у арбитра: {asked}.")
    if proposals:
        # Новый вид заводится решением человека, а не молча в проходе: фасет из
        # сотни одноразовых значений перестаёт отбирать что-либо.
        print("Арбитр предложил виды, которых нет в списке (решать человеку):")
        for name, count in sorted(proposals.items(), key=lambda item: -item[1])[:12]:
            print(f"    {name:40s} {count:4d}")
    if apply_changes:
        print(f"Изменено объектов: {changed}.")
    else:
        print(f"Изменилось бы объектов: {changed}. Это ПОКАЗ; чтобы применить, повторите с --apply.")
    return 0


